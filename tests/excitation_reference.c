struct innovation_scenario {
	const char *name;
	uint16_t positions;
	uint16_t signs;
	int16_t intPitchDelay;
	int16_t boundedGain;
};

static int run_innovation_case(const struct innovation_scenario *sc)
{
	int16_t expected[REF_L_SUB];
	int16_t actual[REF_L_SUB];
	uint16_t pos[4];
	uint16_t jx;
	int16_t baseVector[REF_L_SUB];
	int n;

	ref_fixed_vector(sc->signs, sc->positions, sc->intPitchDelay,
			 sc->boundedGain, expected);
	decodeFixedCodeVector(sc->signs, sc->positions, sc->intPitchDelay,
			      sc->boundedGain, actual);
	ref_pulse_positions(sc->positions, pos, &jx);

	/* full 40 sample comparison: pulse values themselves, not a count */
	for (n = 0; n < REF_L_SUB; n++) {
		TASK_CHECK(actual[n] == expected[n] ||
			   ref_mismatch("innovation.vector", 0, n,
					expected[n], actual[n]));
	}

	/* the jx bit is raw bit 9 of the positions field and selects between
	 * the two last-pulse tracks (3 vs 4 offset) */
	/* bit layout: m0 bits 0-2, m1 bits 3-5, m2 bits 6-8, jx bit 9,
	 * m3 bits 10-12; jx switches the last track between offsets 3 and 4 */
	TASK_CHECK(jx == (uint16_t)((sc->positions >> 9) & 1u) ||
		   ref_mismatch("innovation.jxBit", 0, 3,
				(sc->positions >> 9) & 1u, jx));
	TASK_CHECK(pos[3] == (uint16_t)(5 * ((sc->positions >> 10) & 7u) +
					3 + jx) ||
		   ref_mismatch("innovation.lastTrack", 0, 3,
				5 * ((sc->positions >> 10) & 7u) + 3 + jx,
				pos[3]));

	/* recurrence check on production output: every propagated sample must
	 * be its base pulse plus the rounded contribution one lag behind;
	 * every lag used here is a legal speech lag in [20,143] */
	for (n = 0; n < REF_L_SUB; n++) {
		baseVector[n] = 0;
	}
	for (n = 0; n < 4; n++) {
		baseVector[pos[n]] = (sc->signs >> n & 1u) ?
			REF_Q13_ONE : -REF_Q13_ONE;
	}
	if (sc->intPitchDelay < REF_L_SUB) {
		for (n = sc->intPitchDelay; n < REF_L_SUB; n++) {
			int64_t prod = (int64_t)actual[n - sc->intPitchDelay] *
				       (int64_t)sc->boundedGain;
			int16_t add = (int16_t)((prod + REF_Q14_HALF) >> 14);
			int32_t rebuilt = (int32_t)baseVector[n] +
					  (int32_t)add;
			TASK_CHECK((int32_t)actual[n] == rebuilt ||
				   ref_mismatch("innovation.propagation", 0, n,
						rebuilt, actual[n]));
		}
	}

	return 0;
}

