/*
 * excitation_reference.c
 *
 * Independent fixed-point numerical regression for the bcg729 decoder
 * excitation path: adaptive codebook vector, fixed codebook vector and the
 * per-sample excitation synthesis driven through the public bcg729Decoder.
 *
 * Independence rules kept by this file:
 *  - expected values are derived from standalone arrays, 64 bit integers and
 *    explicit fixed point rounding written here;
 *  - none of the production adaptive codebook, fixed codebook or rounding
 *    macros/functions is used to build an expected value;
 *  - the only production computation reused on purpose is decodeGains(),
 *    called on a decoder context separate from the one under test, because
 *    the gain quantiser is explicitly outside the scope of this independent
 *    proof (see EXCITATION_TESTS.md);
 *  - no output of another bcg729 decoder instance is used as a reference;
 *  - bitstream fields, including the pitch parity bit, are planned from the
 *    field definitions, never generated by the encoder.
 *
 * The file only defines task_cases/task_case_count and the case functions;
 * the runner main() lives in task_support/driver.c.
 */

