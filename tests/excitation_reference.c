/* ------------------------------------------------------------------------- */
/* Frames group: public bcg729Decoder, ten byte speech frames                */
/* ------------------------------------------------------------------------- */

struct frame_plan {
	uint16_t p1, p2;
	uint16_t c1, s1, ga1, gb1;
	uint16_t c2, s2, ga2, gb2;
};

/* Per-channel independent reference state. */
struct frame_reference {
	int16_t history[REF_L_PAST + REF_L_FRAME];
	uint16_t previousIntPitchDelay;
	int16_t boundedGain;
	int boundedGainEverChanged;
	bcg729DecoderChannelContextStruct *gainContext; /* decodeGains only */
};

static void frame_ref_init(struct frame_reference *ref)
{
	memset(ref->history, 0, sizeof(ref->history));
	ref->previousIntPitchDelay = 60;
	ref->boundedGain = REF_BOUND_MIN;
	ref->boundedGainEverChanged = 0;
	ref->gainContext = initBcg729DecoderChannel();
}

/* Build a legal ten byte frame: LSP fields are fixed valid values and the
 * pitch parity bit P0 is planned from the independent parity function. */
static void frame_build_bitstream(const struct frame_plan *plan,
				  uint8_t bitStream[10])
{
	uint16_t parameters[NB_PARAMETERS];
	parameters[0] = 0;   /* L0 */
	parameters[1] = 10;  /* L1 */
	parameters[2] = 5;   /* L2 */
	parameters[3] = 12;  /* L3 */
	parameters[4] = plan->p1;
	parameters[5] = ref_pitch_parity(plan->p1);
	parameters[6] = plan->c1;
	parameters[7] = plan->s1;
	parameters[8] = plan->ga1;
	parameters[9] = plan->gb1;
	parameters[10] = plan->p2;
	parameters[11] = plan->c2;
	parameters[12] = plan->s2;
	parameters[13] = plan->ga2;
	parameters[14] = plan->gb2;
	parametersArray2BitStream(parameters, bitStream);
}

/*
 * One reference subframe: independently synthesised adaptive and fixed
 * vectors, production decodeGains on the separate gain context driven by the
 * reference fixed vector, independent excitation combination. The fixed
 * codebook uses the bounded gain as it was before this subframe; the newly
 * bounded gain is only kept for the next subframe.
 */
static void frame_ref_subframe(struct frame_reference *ref, int subframe,
			       uint16_t pitchIndex, uint16_t positions,
			       uint16_t signs, uint16_t ga, uint16_t gb,
			       int16_t firstDelay,
			       int16_t excitation[REF_L_SUB])
{
	int16_t intDelay, fracDelay;
	int16_t fixedVector[REF_L_SUB];
	int16_t pitchGain = ref->gainContext->adaptativeCodebookGain;
	int16_t fixedGain = ref->gainContext->fixedCodebookGain;
	int offset = REF_L_PAST + subframe * REF_L_SUB;
	int16_t previousBounded = ref->boundedGain;
	int n;

	if (subframe == 0) {
		ref_decode_p1(pitchIndex, &intDelay, &fracDelay);
	} else {
		ref_decode_p2(pitchIndex, firstDelay, &intDelay, &fracDelay);
	}
	ref_adaptive_vector(ref->history, offset, fracDelay, intDelay);
	ref_fixed_vector(signs, positions, intDelay, previousBounded,
			 fixedVector);
	decodeGains(ref->gainContext, ga, gb, fixedVector, 0,
		    &pitchGain, &fixedGain);

	for (n = 0; n < REF_L_SUB; n++) {
		excitation[n] = ref_combine_excitation(
			ref->history[offset + n], fixedVector[n],
			pitchGain, fixedGain);
		ref->history[offset + n] = excitation[n];
	}
	ref->previousIntPitchDelay = (uint16_t)intDelay;
	ref->boundedGain = ref_bound_gain(pitchGain);
	if (ref->boundedGain != previousBounded) {
		ref->boundedGainEverChanged = 1;
	}
}

/*
 * Seven frames per channel. All field widths are legal (P2 <= 31, C <= 8191,
 * S <= 15, GA <= 7, GB <= 15) and the gain indices vary so consecutive
 * bounded gains differ. Lags cover fractional phases and both window clamps.
 */
static const struct frame_plan frame_plans[] = {
	{  42, 15, 1234, 10, 0,  0, 5678,  5, 1,  2 },
	{ 110,  1, 8191, 15, 7, 15, 2730, 12, 6, 14 },
	{ 255, 28, 4817,  3, 3,  8, 1000,  9, 4,  1 },
	{ 196,  2,    0,  0, 2,  4, 8191, 15, 5, 11 },
	{ 197, 16, 3333,  7, 6, 13, 4444,  8, 0, 15 },
	{   1, 31, 7000, 11, 1,  6,  777, 14, 7,  3 },
	{  60, 18, 2222,  6, 4, 10, 5555,  9, 3, 12 }
};
#define FRAME_PLAN_COUNT (sizeof(frame_plans)/sizeof(frame_plans[0]))

static int run_frames_case(void)
{
	bcg729DecoderChannelContextStruct *decA = initBcg729DecoderChannel();
	bcg729DecoderChannelContextStruct *decB = initBcg729DecoderChannel();
	struct frame_reference refA, refB;
	int16_t pcmA[REF_L_FRAME], pcmB[REF_L_FRAME];
	int16_t excA[REF_L_FRAME], excB[REF_L_FRAME];
	size_t f;
	int n;

	TASK_CHECK(decA != NULL);
	TASK_CHECK(decB != NULL);
	frame_ref_init(&refA);
	frame_ref_init(&refB);

	for (f = 0; f < FRAME_PLAN_COUNT; f++) {
		const struct frame_plan *plan = &frame_plans[f];
		uint8_t streamA[10], streamB[10];
		int16_t firstDelayA, firstDelayB;
		int16_t fracDummy;
		unsigned nonzeroA = 0, nonzeroB = 0;

		frame_build_bitstream(plan, streamA);
		frame_build_bitstream(plan, streamB);

		/* reference channel A, both subframes */
		ref_decode_p1(plan->p1, &firstDelayA, &fracDummy);
		frame_ref_subframe(&refA, 0, plan->p1, plan->c1, plan->s1,
				   plan->ga1, plan->gb1, 0, excA);
		frame_ref_subframe(&refA, 1, plan->p2, plan->c2, plan->s2,
				   plan->ga2, plan->gb2, firstDelayA,
				   &excA[REF_L_SUB]);
		memmove(refA.history, &refA.history[REF_L_FRAME],
			REF_L_PAST * sizeof(int16_t));

		/* reference channel B, interleaved on a second instance */
		ref_decode_p1(plan->p1, &firstDelayB, &fracDummy);
		frame_ref_subframe(&refB, 0, plan->p1, plan->c1, plan->s1,
				   plan->ga1, plan->gb1, 0, excB);
		frame_ref_subframe(&refB, 1, plan->p2, plan->c2, plan->s2,
				   plan->ga2, plan->gb2, firstDelayB,
				   &excB[REF_L_SUB]);
		memmove(refB.history, &refB.history[REF_L_FRAME],
			REF_L_PAST * sizeof(int16_t));

		/* production decoders, interleaved, public ten byte path */
		bcg729Decoder(decA, streamA, 10, 0, 0, 0, pcmA);
		bcg729Decoder(decB, streamB, 10, 0, 0, 0, pcmB);

		/* the 80 excitation samples of this frame survive the decoder
		 * shift at history indices 74..153 */
		for (n = REF_L_PAST - REF_L_FRAME; n < REF_L_PAST; n++) {
			TASK_CHECK(decA->excitationVector[n] == refA.history[n] ||
				   ref_mismatch("frames.A.frameExcitation", 1,
						n, refA.history[n],
						decA->excitationVector[n]));
			TASK_CHECK(decB->excitationVector[n] == refB.history[n] ||
				   ref_mismatch("frames.B.frameExcitation", 1,
						n, refB.history[n],
						decB->excitationVector[n]));
		}
		/* full retained pitch history */
		for (n = 0; n < REF_L_PAST; n++) {
			TASK_CHECK(decA->excitationVector[n] == refA.history[n] ||
				   ref_mismatch("frames.A.pitchHistory", 1, n,
						refA.history[n],
						decA->excitationVector[n]));
			TASK_CHECK(decB->excitationVector[n] == refB.history[n] ||
				   ref_mismatch("frames.B.pitchHistory", 1, n,
						refB.history[n],
						decB->excitationVector[n]));
		}
		TASK_CHECK(decA->previousIntPitchDelay == refA.previousIntPitchDelay ||
			   ref_mismatch("frames.A.previousIntPitchDelay", 1, 0,
					refA.previousIntPitchDelay,
					decA->previousIntPitchDelay));
		TASK_CHECK(decB->previousIntPitchDelay == refB.previousIntPitchDelay ||
			   ref_mismatch("frames.B.previousIntPitchDelay", 1, 0,
					refB.previousIntPitchDelay,
					decB->previousIntPitchDelay));
		TASK_CHECK(decA->boundedAdaptativeCodebookGain == refA.boundedGain ||
			   ref_mismatch("frames.A.boundedGain", 1, 0,
					refA.boundedGain,
					decA->boundedAdaptativeCodebookGain));
		TASK_CHECK(decB->boundedAdaptativeCodebookGain == refB.boundedGain ||
			   ref_mismatch("frames.B.boundedGain", 1, 0,
					refB.boundedGain,
					decB->boundedAdaptativeCodebookGain));

		/* continuous non-zero PCM, checked on every frame */
		for (n = 0; n < REF_L_FRAME; n++) {
			nonzeroA += (pcmA[n] != 0);
			nonzeroB += (pcmB[n] != 0);
		}
		TASK_CHECK(nonzeroA > 0 ||
			   ref_mismatch("frames.A.pcmNonZero", 1, 0, 1, 0));
		TASK_CHECK(nonzeroB > 0 ||
			   ref_mismatch("frames.B.pcmNonZero", 1, 0, 1, 0));
	}

	/* the sequence must contain subframes where the new bounded gain
	 * differs from the previous one on both instances */
	TASK_CHECK(refA.boundedGainEverChanged ||
		   ref_mismatch("frames.A.boundedGainChange", 1, 0, 1, 0));
	TASK_CHECK(refB.boundedGainEverChanged ||
		   ref_mismatch("frames.B.boundedGainChange", 1, 0, 1, 0));

	closeBcg729DecoderChannel(decA);
	closeBcg729DecoderChannel(decB);
	closeBcg729DecoderChannel(refA.gainContext);
	closeBcg729DecoderChannel(refB.gainContext);
	return 0;
}

