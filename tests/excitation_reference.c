struct pitch_scenario {
	const char *name;
	uint16_t p1;
	uint16_t p2;
	uint8_t parityFlag;
	uint8_t frameErasure;
	uint16_t initialPrevDelay;
};

static int run_pitch_case(const struct pitch_scenario *sc)
{
	/* Reference state: full 234 entry buffer, 154 history + 80 current. */
	int16_t refBuf[REF_L_PAST + REF_L_FRAME];
	int16_t expSub1[REF_L_SUB], expSub2[REF_L_SUB];
	int16_t refInt1 = 0, refFrac1 = 0, refInt2 = 0, refFrac2 = 0;
	uint16_t refPrevDelay = sc->initialPrevDelay;

	/* Production state. */
	bcg729DecoderChannelContextStruct *ctx = initBcg729DecoderChannel();
	int16_t prodInt = 0;
	int n;

	TASK_CHECK(ctx != NULL);
	ref_load_history(refBuf);
	memcpy(ctx->excitationVector, refBuf, REF_L_PAST * sizeof(int16_t));
	ctx->previousIntPitchDelay = sc->initialPrevDelay;

	/* ---- subframe 1 ---- */
	if (sc->parityFlag || sc->frameErasure) {
		refInt1 = (int16_t)refPrevDelay;
		refFrac1 = 0;
		refPrevDelay++;
		if (refPrevDelay > REF_MAX_INT_DELAY) {
			refPrevDelay = REF_MAX_INT_DELAY;
		}
	} else {
		ref_decode_p1(sc->p1, &refInt1, &refFrac1);
		refPrevDelay = (uint16_t)refInt1;
	}
	ref_adaptive_vector(refBuf, REF_L_PAST, refFrac1, refInt1);
	for (n = 0; n < REF_L_SUB; n++) {
		expSub1[n] = refBuf[REF_L_PAST + n];
	}

	decodeAdaptativeCodeVector(ctx, 0, sc->p1, sc->parityFlag,
				   sc->frameErasure, &prodInt,
				   &ctx->excitationVector[REF_L_PAST]);
	TASK_CHECK(prodInt == refInt1 ||
		   ref_mismatch("pitch.sf1.intDelay", 0, 0, refInt1, prodInt));
	TASK_CHECK(ctx->previousIntPitchDelay == refPrevDelay ||
		   ref_mismatch("pitch.sf1.previousIntPitchDelay", 0, 0,
				refPrevDelay, ctx->previousIntPitchDelay));
	for (n = 0; n < REF_L_SUB; n++) {
		int16_t got = ctx->excitationVector[REF_L_PAST + n];
		TASK_CHECK(got == expSub1[n] ||
			   ref_mismatch("pitch.sf1.vector", 0, n,
					expSub1[n], got));
	}

	/* ---- subframe 2 ---- */
	if (sc->frameErasure) {
		refInt2 = (int16_t)refPrevDelay;
		refFrac2 = 0;
		refPrevDelay++;
		if (refPrevDelay > REF_MAX_INT_DELAY) {
			refPrevDelay = REF_MAX_INT_DELAY;
		}
	} else {
		/* a parity error only acts on the first subframe */
		ref_decode_p2(sc->p2, refInt1, &refInt2, &refFrac2);
		refPrevDelay = (uint16_t)refInt2;
	}
	ref_adaptive_vector(refBuf, REF_L_PAST + REF_L_SUB, refFrac2, refInt2);
	for (n = 0; n < REF_L_SUB; n++) {
		expSub2[n] = refBuf[REF_L_PAST + REF_L_SUB + n];
	}

	decodeAdaptativeCodeVector(ctx, REF_L_SUB, sc->p2, sc->parityFlag,
				   sc->frameErasure, &prodInt,
				   &ctx->excitationVector[REF_L_PAST + REF_L_SUB]);
	TASK_CHECK(prodInt == refInt2 ||
		   ref_mismatch("pitch.sf2.intDelay", 1, 0, refInt2, prodInt));
	TASK_CHECK(ctx->previousIntPitchDelay == refPrevDelay ||
		   ref_mismatch("pitch.sf2.previousIntPitchDelay", 1, 0,
				refPrevDelay, ctx->previousIntPitchDelay));
	for (n = 0; n < REF_L_SUB; n++) {
		int16_t got = ctx->excitationVector[REF_L_PAST + REF_L_SUB + n];
		TASK_CHECK(got == expSub2[n] ||
			   ref_mismatch("pitch.sf2.vector", 1, n,
					expSub2[n], got));
	}

	/* the 154 word pitch history must stay untouched in both subframes */
	for (n = 0; n < REF_L_PAST; n++) {
		TASK_CHECK(ctx->excitationVector[n] == refBuf[n] ||
			   ref_mismatch("pitch.history", 1, n,
					refBuf[n], ctx->excitationVector[n]));
	}

	closeBcg729DecoderChannel(ctx);
	return 0;
}

