#define REF_L_PAST 154          /* L_PAST_EXCITATION, restated locally       */
#define REF_L_FRAME 80
#define REF_L_SUB 40
#define REF_Q13_ONE 8192
#define REF_Q14_HALF 8192       /* rounding term for a Q14 product           */
#define REF_Q15_HALF 16384      /* rounding term for a Q15 product           */
#define REF_MAX_INT_DELAY 143
#define REF_BOUND_MIN 3277      /* BOUNDED_PITCH_GAIN_MIN/MAX restated       */
#define REF_BOUND_MAX 13107

/* b30 interpolation filter, ITU G.729 3.7.1 table, transcribed independently
 * in this test file (Q0.15). The production table in codebooks.c is never
 * read by the reference computation. */
static const int16_t ref_b30[31] = {
	29443, 25207, 14701, 3143, -4402, -5850, -2783, 1211, 3130, 2259,
	0,
	-1652, -1666, -464, 756, 1099, 550, -245, -634, -451,
	0,
	308, 296, 78, -120, -165, -79, 34, 91, 70,
	0
};

/* Deterministic, small amplitude history pattern: every value stays well
 * inside 16 bit range even after the interpolation accumulation. */
static int16_t ref_history_sample(int index)
{
	int v = ((index * 37) % 211) - 105;          /* -105..105 */
	return (int16_t)((v == 0) ? (7 + (index & 3)) : v);
}

static void ref_load_history(int16_t *buf)
{
	int i;
	for (i = 0; i < REF_L_PAST; i++) {
		buf[i] = ref_history_sample(i);
	}
}

static int16_t ref_saturate16(int64_t x)
{
	if (x > 32767) {
		return 32767;
	}
	if (x < -32768) {
		return -32768;
	}
	return (int16_t)x;
}

static int16_t ref_saturate16_32(int32_t x)
{
	if (x > 32767) {
		return 32767;
	}
	if (x < -32768) {
		return -32768;
	}
	return (int16_t)x;
}

/* Independent parity of the 8 bit pitch index P1: XOR of the six upper bits,
 * seeded with 1, derived from the bit field definition. */
static uint16_t ref_pitch_parity(uint16_t index)
{
	uint16_t parity = 1;
	uint16_t v = index >> 2;
	int i;
	for (i = 0; i < 6; i++) {
		parity ^= (uint16_t)(v & 1u);
		v >>= 1;
	}
	return parity;
}

/*
 * First subframe absolute pitch index decoding (spec 4.1.3).
 * Writes the integer delay and the fractional delay in {-1,0,1}.
 * The division by three is written explicitly rather than through the
 * production Q15 multiply.
 */
static void ref_decode_p1(uint16_t p1, int16_t *intDelay, int16_t *fracDelay)
{
	if (p1 < 197) {
		int k = (p1 + 2) / 3 + 19;
		int t = p1 - 3 * k + 58;
		*intDelay = (int16_t)k;
		*fracDelay = (int16_t)t;
	} else {
		*intDelay = (int16_t)(p1 - 112);
		*fracDelay = 0;
	}
}

/*
 * Second subframe relative decoding: the integer window opens five samples
 * below the first subframe delay, clamped to [20,134], and the relative index
 * adds a delta of -1..10 on top of that window base.
 */
static void ref_decode_p2(uint16_t p2, int16_t firstIntDelay,
			  int16_t *intDelay, int16_t *fracDelay)
{
	int tMin = firstIntDelay - 5;
	int rel;
	if (tMin < 20) {
		tMin = 20;
	}
	if (tMin > 134) {
		tMin = 134;
	}
	rel = (p2 + 2) / 3 - 1;
	*fracDelay = (int16_t)(p2 - 2 - 3 * rel);
	*intDelay = (int16_t)(rel + tMin);
}

/*
 * Independent adaptive codebook interpolation, sample by sample, on a full
 * excitation buffer whose current subframe starts at buf[offset]. Already
 * generated samples of the current subframe are read back through the same
 * buffer when the lag is short, so the causal update order is part of the
 * computation rather than a snapshot convolution over old history.
 *
 * The fractional sign selects the base point and filter phases:
 *   frac  0 -> base n-k,       phases b30(0..) and b30(3..)
 *   frac -1 -> base n-k,       phases b30(1..) and b30(2..)
 *   frac +1 -> base n-(k+1),   phases b30(2..) and b30(1..)
 */
static void ref_adaptive_vector(int16_t *buf, int offset,
				int16_t fracDelay, int16_t intDelay)
{
	int t, baseShift;
	int n, i;
	if (fracDelay == 1) {
		t = 2;
		baseShift = -(intDelay + 1);
	} else {
		t = -fracDelay; /* 0 -> 0, -1 -> 1 */
		baseShift = -intDelay;
	}
	for (n = 0; n < REF_L_SUB; n++) {
		int64_t acc = 0;
		int base = offset + baseShift + n;
		for (i = 0; i < 10; i++) {
			int j = 3 * i;
			acc += (int64_t)buf[base - i] * ref_b30[t + j];
			acc += (int64_t)buf[base + 1 + i] * ref_b30[3 - t + j];
		}
		/* Q15 accumulation, half up rounding, 16 bit saturation */
		buf[offset + n] = ref_saturate16((acc + REF_Q15_HALF) >> 15);
	}
}

/* Independent pulse track decoding: four 3 bit position fields and the extra
 * jx bit selecting the last pulse track. */
static void ref_pulse_positions(uint16_t positions, uint16_t pos[4],
				uint16_t *jx)
{
	pos[0] = (positions & 7u) * 5;
	positions >>= 3;
	pos[1] = (positions & 7u) * 5 + 1;
	positions >>= 3;
	pos[2] = (positions & 7u) * 5 + 2;
	positions >>= 3;
	*jx = positions & 1u;
	positions >>= 1;
	pos[3] = (positions & 7u) * 5 + 3 + *jx;
}

/*
 * Fixed codebook vector in Q13: base pulses first, then the pitch sharpening
 * propagation of eq48 applied in ascending sample order with explicit Q14
 * half-up rounding. Already propagated values feed later samples.
 */
static void ref_fixed_vector(uint16_t signs, uint16_t positions,
			     int16_t intPitchDelay, int16_t boundedPitchGain,
			     int16_t fixedVector[REF_L_SUB])
{
	uint16_t pos[4];
	uint16_t jx;
	int i;
	ref_pulse_positions(positions, pos, &jx);
	for (i = 0; i < REF_L_SUB; i++) {
		fixedVector[i] = 0;
	}
	for (i = 0; i < 4; i++) {
		fixedVector[pos[i]] = (signs & 1u) ? REF_Q13_ONE : -REF_Q13_ONE;
		signs >>= 1;
	}
	for (i = intPitchDelay; i < REF_L_SUB; i++) {
		int64_t prod = (int64_t)fixedVector[i - intPitchDelay] *
			       (int64_t)boundedPitchGain;
		int16_t add = (int16_t)((prod + REF_Q14_HALF) >> 14);
		fixedVector[i] = ref_saturate16_32(
			(int32_t)fixedVector[i] + (int32_t)add);
	}
}

/* Excitation combination eq75, independently rounded on 64 bits. */
static int16_t ref_combine_excitation(int16_t adaptive, int16_t fixed,
				      int16_t pitchGain, int16_t fixedGain)
{
	int64_t acc = (int64_t)adaptive * (int64_t)pitchGain
		    + (int64_t)fixed * (int64_t)fixedGain;
	return ref_saturate16((acc + REF_Q14_HALF) >> 14);
}

static int16_t ref_bound_gain(int16_t gain)
{
	if (gain > REF_BOUND_MAX) {
		return REF_BOUND_MAX;
	}
	if (gain < REF_BOUND_MIN) {
		return REF_BOUND_MIN;
	}
	return gain;
}

/* Mismatch reporter: returns 0 so TASK_CHECK(mismatch(...)) records a failure
 * and the runner exits with status 4 after printing the divergent values. */
static int ref_mismatch(const char *stage, int subframe, int sample,
			long long expected, long long actual)
{
	printf("CONTENT_MISMATCH stage=%s subframe=%d sample=%d "
	       "expected=%lld actual=%lld\n",
	       stage, subframe, sample, expected, actual);
	return 0;
}

