// Native (desktop) counterpart of examples/DecodeFromProgmem and
// examples/EncodeSyntheticFrame's built-in benchmarks - same clip, same
// synthetic gradient, same repetition counts and first-frame exclusion, just
// timed with std::chrono instead of Arduino's micros(), so this project's
// README/docs/memory-budget.md can report real x86 numbers alongside the
// real ESP32 ones without fabricating either. Not a correctness test (no
// assertions, not added to CTest in CMakeLists.txt) - build/run manually:
//   cmake --build build --target bench_native && ./build/test/native/bench_native
#include <chrono>
#include <cstdint>
#include <cstdio>

#include "TinyMPGDecoder.h"
#include "TinyMPGEncoder.h"

using namespace tinympg;

static uint64_t nowUs() {
  return std::chrono::duration_cast<std::chrono::microseconds>(
             std::chrono::steady_clock::now().time_since_epoch())
      .count();
}

