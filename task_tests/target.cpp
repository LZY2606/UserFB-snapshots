/* Task tests for bcdec_bc7_transform().

   Registered groups:
     modes       - all eight BC7 modes, forward pixel equivalence, identity,
                   stability, invalid inputs
     partitions  - exhaustive structural representability from the standard
                   partition tables, smallest-partition tie break, mode 0 limit
     anchors     - fix-up anchor MSB rule, color/alpha stream independence
     integration - in-place, failure preservation, inverse, 8x8 tiling, PPM

   All blocks are generated by the independent bit writer below; the decoded
   pixels are always produced by the original bcdec_bc7(), never by the
   transform code, and compared against an independent pixel permutation. */

