/* modes                                                                   */

void TestModes(Case& c) {
    c.check(BCDEC_TRANSFORM_INVALID != BCDEC_TRANSFORM_OK, "status values are distinct");
    for (int mode = 0; mode < 8; ++mode) {
        const int parts = PartitionCount(mode);
        for (int part = 0; part < parts; ++part) {
            for (int rot = 0; rot < ((mode == 4 || mode == 5) ? 4 : 1); ++rot) {
                for (int isel = 0; isel < (mode == 4 ? 2 : 1); ++isel) {
                    BlockConfig cfg;
                    cfg.mode = mode;
                    cfg.partition = part;
                    cfg.rotation = rot;
                    cfg.index_selection = isel;
                    cfg.random_endpoints = (part % 2) != 0;
                    cfg.nonzero = (part % 3) == 0;
                    cfg.seed = static_cast<std::uint32_t>(1 + mode * 131 + part * 7 + rot * 3 + isel);

                    std::vector<unsigned char> src = MakeBlock(cfg);
                    std::vector<unsigned char> decoded = DecodeBlock(src);
                    c.check(decoded.size() == 64, "decoder produced a block");

                    for (int o = 0; o < 8; ++o) {
                        bcdec_transform_op op = static_cast<bcdec_transform_op>(o);
                        bcdec_transform_status st = CheckPixels(c, src, op);
                        if (st == BCDEC_TRANSFORM_UNREPRESENTABLE) {
                            c.check(SubsetsOf(mode) > 1,
                                    "single subset modes must never be unrepresentable");
                        }
                    }

                    /* header fields are preserved */
                    std::vector<unsigned char> rot90 = RunTransform(src, BCDEC_ROTATE_90);
                    if (rot90.size() == 16 && rot90[0] != 0xEE) {
                        c.check(HeaderField(rot90, 0, mode + 1) == (1 << mode),
                                "mode prefix preserved");
                        if (mode == 4 || mode == 5) {
                            int off = mode + 1;
                            c.check(HeaderField(rot90, off, 2) == rot, "channel rotation preserved");
                            if (mode == 4) {
                                c.check(HeaderField(rot90, off + 2, 1) == isel,
                                        "mode 4 index-selection bit preserved");
                            }
                        }
                    }

                    /* identity is byte exact and repeated runs are stable */
                    std::vector<unsigned char> identity = RunTransform(src, BCDEC_IDENTITY);
                    c.check(identity == src, "identity must reproduce the source bytes");
                    std::vector<unsigned char> again = RunTransform(src, BCDEC_ROTATE_90);
                    std::vector<unsigned char> again2 = RunTransform(src, BCDEC_ROTATE_90);
                    c.check(again == again2, "repeated runs of the same operation are stable");
                }
            }
        }
    }

    /* invalid inputs */
    std::vector<unsigned char> valid = MakeBlock(BlockConfig{});
    std::vector<unsigned char> sentinel(16, 0xAB);
    c.check(bcdec_bc7_transform(nullptr, sentinel.data(), BCDEC_ROTATE_90) ==
                BCDEC_TRANSFORM_INVALID, "null source is invalid");
    c.check(bcdec_bc7_transform(valid.data(), nullptr, BCDEC_ROTATE_90) ==
                BCDEC_TRANSFORM_INVALID, "null destination is invalid");
    c.check(bcdec_bc7_transform(valid.data(), sentinel.data(),
                                static_cast<bcdec_transform_op>(42)) == BCDEC_TRANSFORM_INVALID,
            "unknown operation is invalid");
    {
        std::vector<unsigned char> zero(16, 0);
        std::vector<unsigned char> keep(16, 0xCD);
        c.check(bcdec_bc7_transform(zero.data(), keep.data(), BCDEC_ROTATE_90) ==
                    BCDEC_TRANSFORM_INVALID, "block without a valid mode is invalid");
        c.check(keep == std::vector<unsigned char>(16, 0xCD),
                "invalid input must not modify the destination");
    }
}

