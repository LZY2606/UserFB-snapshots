/* integration                                                             */

void TestIntegration(Case& c) {
    /* in-place must equal out-of-place for every op on a multi-subset block */
    for (int mode : { 0, 2, 1, 7 }) {
        std::vector<unsigned char> src =
            MakeBlock(BlockConfig{mode, 1 % PartitionCount(mode), 0, 0, true, true, 55u});
        for (int o = 0; o < 8; ++o) {
            bcdec_transform_op op = static_cast<bcdec_transform_op>(o);
            std::vector<unsigned char> out(16, 0);
            std::vector<unsigned char> inplace = src;
            bcdec_transform_status a = bcdec_bc7_transform(src.data(), out.data(), op);
            bcdec_transform_status b = bcdec_bc7_transform(inplace.data(), inplace.data(), op);
            c.check(a == b, "in-place and out-of-place status agree");
            if (a == BCDEC_TRANSFORM_OK) {
                c.check(inplace == out, "in-place result equals out-of-place result");
            }
        }
    }

    /* failure keeps every destination byte */
    {
        std::vector<unsigned char> bad(16, 0);  /* no mode bits */
        std::vector<unsigned char> dst(16, 0x5A);
        for (int o = 0; o < 8; ++o) {
            c.check(bcdec_bc7_transform(bad.data(), dst.data(), static_cast<bcdec_transform_op>(o)) ==
                        BCDEC_TRANSFORM_INVALID, "all-zero block is invalid");
            c.check(dst == std::vector<unsigned char>(16, 0x5A), "sentinel intact after invalid");
        }
    }
    {
        std::vector<unsigned char> src = MakeBlock(BlockConfig{0, 14, 0, 0, false, false, 9});
        std::vector<unsigned char> dst(16, 0xD3);
        c.check(bcdec_bc7_transform(src.data(), dst.data(), BCDEC_ROTATE_180) ==
                    BCDEC_TRANSFORM_UNREPRESENTABLE, "mode 0 partition 14 / 180 is unrepresentable");
        c.check(dst == std::vector<unsigned char>(16, 0xD3), "sentinel intact after failure");
    }

    /* applying an operation and its inverse returns the original pixels */
    struct InversePair { bcdec_transform_op a, b; };
    const InversePair pairs[] = {
        { BCDEC_ROTATE_90, BCDEC_ROTATE_270 },
        { BCDEC_ROTATE_270, BCDEC_ROTATE_90 },
        { BCDEC_ROTATE_180, BCDEC_ROTATE_180 },
        { BCDEC_FLIP_X, BCDEC_FLIP_X },
        { BCDEC_FLIP_Y, BCDEC_FLIP_Y },
        { BCDEC_TRANSPOSE, BCDEC_TRANSPOSE },
        { BCDEC_ANTI_TRANSPOSE, BCDEC_ANTI_TRANSPOSE },
    };
    for (int mode : { 0, 1, 2, 3, 7, 4, 5, 6 }) {
        std::vector<unsigned char> src =
            MakeBlock(BlockConfig{mode, 0, 0, 0, true, true, 91u});
        std::vector<unsigned char> original = DecodeBlock(src);
        for (const InversePair& p : pairs) {
            std::vector<unsigned char> mid(16, 0), back(16, 0);
            if (bcdec_bc7_transform(src.data(), mid.data(), p.a) != BCDEC_TRANSFORM_OK) continue;
            if (bcdec_bc7_transform(mid.data(), back.data(), p.b) != BCDEC_TRANSFORM_OK) continue;
            std::vector<unsigned char> pixels = DecodeBlock(back);
            c.check(pixels == original,
                    (std::string("inverse pair must restore pixels for mode ") +
                     std::to_string(mode)).c_str());
            /* self-inverse ops must restore the exact compressed bytes too:
               the second pass has to undo the endpoint flips as well */
            if (p.a == p.b) {
                c.check(back == src,
                        (std::string("self-inverse op must restore bytes for mode ") +
                         std::to_string(mode)).c_str());
            }
        }
    }

    /* 8x8 texture built from four transformable blocks: rotate the whole image
       by 90 degrees, moving block positions and pixels inside each block. */
    {
        std::vector<unsigned char> blocks[4];
        for (int i = 0; i < 4; ++i) {
            blocks[i] = MakeBlock(BlockConfig{4, 0, 0, 0, true, true,
                                              static_cast<std::uint32_t>(300 + i * 17)});
        }
        /* 2x2 blocks -> 8x8 pixels */
        std::vector<unsigned char> image(64 * 64, 0);
        for (int b = 0; b < 4; ++b) {
            std::vector<unsigned char> px = DecodeBlock(blocks[b]);
            int bx = b % 2, by = b / 2;
            for (int y = 0; y < 4; ++y) {
                for (int x = 0; x < 4; ++x) {
                    std::memcpy(&image[((by * 4 + y) * 8 + (bx * 4 + x)) * 4],
                                &px[(y * 4 + x) * 4], 4);
                }
            }
        }

        /* reference: rotate the 8x8 image 90 degrees, source (x,y)->(7-y,x) */
        std::vector<unsigned char> want(64 * 64, 0);
        for (int y = 0; y < 8; ++y) {
            for (int x = 0; x < 8; ++x) {
                std::memcpy(&want[((x) * 8 + (7 - y)) * 4], &image[(y * 8 + x) * 4], 4);
            }
        }

        /* transform block positions: output block (bx,by) takes source block
           (by, 1-bx); each block is rotated 90 degrees internally */
        std::vector<unsigned char> outBlocks[4];
        for (int b = 0; b < 4; ++b) {
            int bx = b % 2, by = b / 2;
            /* source block that lands here */
            int sbx = by, sby = 1 - bx;
            int sb = sby * 2 + sbx;
            outBlocks[b].assign(16, 0);
            c.check(bcdec_bc7_transform(blocks[sb].data(), outBlocks[b].data(), BCDEC_ROTATE_90) ==
                        BCDEC_TRANSFORM_OK, "tile block transform succeeds");
        }
        std::vector<unsigned char> got(64 * 64, 0);
        for (int b = 0; b < 4; ++b) {
            std::vector<unsigned char> px = DecodeBlock(outBlocks[b]);
            int bx = b % 2, by = b / 2;
            for (int y = 0; y < 4; ++y) {
                for (int x = 0; x < 4; ++x) {
                    std::memcpy(&got[((by * 4 + y) * 8 + (bx * 4 + x)) * 4],
                                &px[(y * 4 + x) * 4], 4);
                }
            }
        }
        c.check(got == want, "8x8 texture: block positions and pixels both rotated");

        /* emit a small PPM of the rotated image */
        std::FILE* f = std::fopen("task_tests/transform_8x8.ppm", "wb");
        c.check(f != nullptr, "PPM file can be opened");
        if (f) {
            std::fprintf(f, "P6\n8 8\n255\n");
            for (int i = 0; i < 64; ++i) {
                unsigned char rgb[3] = { got[i * 4], got[i * 4 + 1], got[i * 4 + 2] };
                std::fwrite(rgb, 1, 3, f);
            }
            std::fclose(f);
            c.check(true, "PPM written");
        }
    }
}

