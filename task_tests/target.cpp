/* partitions                                                              */

void TestPartitions(Case& c) {
    const char* names[8] = { "IDENTITY", "ROTATE_90", "ROTATE_180", "ROTATE_270",
                             "FLIP_X", "FLIP_Y", "TRANSPOSE", "ANTI_TRANSPOSE" };
    for (int mode = 0; mode < 8; ++mode) {
        if (SubsetsOf(mode) == 1) continue;
        const int parts = PartitionCount(mode);
        for (int part = 0; part < parts; ++part) {
            for (int o = 0; o < 8; ++o) {
                bcdec_transform_op op = static_cast<bcdec_transform_op>(o);
                int expected = (op == BCDEC_IDENTITY) ? part : StructurallyRepresentable(mode, part, op);
                if (op == BCDEC_IDENTITY) expected = part;

                std::vector<unsigned char> block = MakeBlock(
                    BlockConfig{mode, part, static_cast<int>(op) % 4, 0, true, true,
                                static_cast<std::uint32_t>(7 + mode * 31 + part * 3 + o)});
                std::vector<unsigned char> dst(16, 0x77);
                bcdec_transform_status st = bcdec_bc7_transform(block.data(), dst.data(), op);

                if (expected < 0) {
                    c.check(st == BCDEC_TRANSFORM_UNREPRESENTABLE,
                            (std::string("expected UNREPRESENTABLE for mode ") +
                             std::to_string(mode) + " partition " + std::to_string(part) + " " +
                             names[o]).c_str());
                    c.check(dst == std::vector<unsigned char>(16, 0x77),
                            "unrepresentable must not touch the destination");
                } else {
                    c.check(st == BCDEC_TRANSFORM_OK,
                            (std::string("expected OK for mode ") + std::to_string(mode) +
                             " partition " + std::to_string(part) + " " + names[o]).c_str());
                    /* the chosen partition must be the smallest one that works */
                    int chosen;
                    if (mode == 0) chosen = HeaderField(dst, mode + 1, 4);
                    else chosen = HeaderField(dst, mode + 1, 6);
                    c.check(chosen == expected, "must choose the numerically smallest partition");
                    c.check(expected == StructurallyRepresentable(mode, part, op),
                            "chosen partition must be structurally valid");
                }
            }
        }
    }

    /* the documented impossible case: mode 0 partition 14 rotated by 180 */
    {
        std::vector<unsigned char> block =
            MakeBlock(BlockConfig{0, 14, 0, 0, false, false, 11});
        std::vector<unsigned char> dst(16, 0x33);
        c.check(bcdec_bc7_transform(block.data(), dst.data(), BCDEC_ROTATE_180) ==
                    BCDEC_TRANSFORM_UNREPRESENTABLE,
                "mode 0 partition 14 rotated 180 degrees is not representable");
        c.check(dst == std::vector<unsigned char>(16, 0x33), "failed transform keeps destination");
        /* and the same partition under identity still works */
        c.check(bcdec_bc7_transform(block.data(), dst.data(), BCDEC_IDENTITY) == BCDEC_TRANSFORM_OK,
                "the same block under identity is fine");
    }

    /* all colors identical must NOT relax the structural rule */
    {
        std::vector<unsigned char> block =
            MakeBlock(BlockConfig{0, 14, 0, 0, false, false, 5});
        /* force all endpoints equal: build a fresh block with identical endpoint fields */
        BitWriter w;
        w.put(1u << 0, 1);
        w.put(14, 4);
        for (int c = 0; c < 3; ++c) for (int e = 0; e < 6; ++e) w.put(5, 4);
        for (int e = 0; e < 6; ++e) w.put(0, 1);
        for (int y = 0; y < 4; ++y) for (int x = 0; x < 4; ++x) {
            w.put(0, 3 - (IsAnchor(0, 14, x, y) ? 1 : 0));
        }
        std::vector<unsigned char> flat = w.bytes;
        std::vector<unsigned char> dst(16, 0x44);
        c.check(bcdec_bc7_transform(flat.data(), dst.data(), BCDEC_ROTATE_180) ==
                    BCDEC_TRANSFORM_UNREPRESENTABLE,
                "flat colors do not make an unrepresentable layout representable");
        c.check(dst == std::vector<unsigned char>(16, 0x44), "failure preserves destination");
        (void)block;
    }

    /* mode 0 may only use partitions 0..15, mode 2/3/7 may use all 64 */
    for (int mode : { 2, 3, 7 }) {
        bool found_high = false;
        for (int part = 0; part < 64 && !found_high; ++part) {
            std::vector<unsigned char> block =
                MakeBlock(BlockConfig{mode, part, 0, 0, true, true, 17u + part});
            std::vector<unsigned char> dst(16, 0);
            if (bcdec_bc7_transform(block.data(), dst.data(), BCDEC_TRANSPOSE) == BCDEC_TRANSFORM_OK) {
                int chosen = HeaderField(dst, mode + 1, 6);
                if (chosen >= 16) found_high = true;
            }
        }
        c.check(found_high, "modes with a 6 bit partition field may select partitions above 15");
    }
}

