/* anchors                                                                 */

/* Extract the selector streams from a decoded block by re-deriving the header.
   Returns false if the block has no valid mode. */
struct ParsedBlock {
    int mode = -1;
    int partition = 0;
    std::vector<int> selectors;   /* 16 primary selector values, un-truncated */
    int primary_bits = 0;
};

bool ParseSelectors(const std::vector<unsigned char>& block, ParsedBlock* out, bool alpha_stream) {
    int mode = 0;
    while (mode < 8 && (block[0] & (1u << mode)) == 0) ++mode;
    if (mode >= 8) return false;
    out->mode = mode;
    int pos = mode + 1;
    int subsets = SubsetsOf(mode);
    if (subsets > 1) {
        int nbits = (mode == 0) ? 4 : 6;
        out->partition = HeaderField(block, pos, nbits);
        pos += nbits;
    }
    if (mode == 4 || mode == 5) {
        pos += 2;
        if (mode == 4) pos += 1;
    }
    int endpoints = subsets * 2;
    pos += 3 * endpoints * kRgbBits[mode];
    pos += endpoints * kAlphaBits[mode];
    if (mode == 1) pos += subsets;
    else if (kHasPBits[mode]) pos += endpoints;

    bool secondary = alpha_stream && kSecondary[mode] > 0;
    int bits = secondary ? kSecondary[mode] : kPrimary[mode];
    if (secondary) {
        /* skip the primary stream first */
        for (int y = 0; y < 4; ++y) for (int x = 0; x < 4; ++x) {
            pos += kPrimary[mode] - (IsAnchor(mode, out->partition, x, y) ? 1 : 0);
        }
    }
    out->selectors.assign(16, 0);
    out->primary_bits = bits;
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 4; ++x) {
            int nb = bits - (IsAnchor(mode, out->partition, x, y) ? 1 : 0);
            out->selectors[y * 4 + x] = HeaderField(block, pos, nb);
            pos += nb;
        }
    }
    return true;
}

void TestAnchors(Case& c) {
    /* Fixed counterexample. In a mode 2 block using partition 0, rotation by 90
       degrees moves source pixel (0, 3) onto output pixel (0, 0), which is the
       fix-up anchor of the output partition. Source (0, 3) is not an anchor of
       partition 0, so its selector is stored with the full two bits and may
       have the MSB set. Copying it verbatim would put a 1 into the bit the
       format omits for anchors. The transform has to flip that subset's
       endpoint pair and complement its selectors instead. */
    {
        BitWriter w;
        w.put(1u << 2, 3);
        w.put(0, 6);
        /* mode 2 has no p-bits, so the selectors start immediately */
        for (int cc = 0; cc < 3; ++cc) for (int e = 0; e < 6; ++e) w.put((unsigned)(cc * 5 + e), 5);
        for (int y = 0; y < 4; ++y) {
            for (int x = 0; x < 4; ++x) {
                int v = 0;
                if (x == 0 && y == 3) v = 2;   /* lands on the anchor under ROTATE_90 */
                if (x == 2 && y == 1) v = 3;
                if (x == 1 && y == 2) v = 1;
                w.put((unsigned)v, 2 - (IsAnchor(2, 0, x, y) ? 1 : 0));
            }
        }
        std::vector<unsigned char> block = w.bytes;
        ParsedBlock source;
        c.check(ParseSelectors(block, &source, false), "counterexample source parses");
        c.check(source.selectors[3 * 4 + 0] >= (1 << (source.primary_bits - 1)),
                "counterexample really carries an anchor-MSB selector");

        for (int o = 1; o < 8; ++o) {
            bcdec_transform_op op = static_cast<bcdec_transform_op>(o);
            std::vector<unsigned char> dst(16, 0);
            bcdec_transform_status st = bcdec_bc7_transform(block.data(), dst.data(), op);
            if (st != BCDEC_TRANSFORM_OK) {
                c.check(st == BCDEC_TRANSFORM_UNREPRESENTABLE,
                        "counterexample either transforms or is structurally impossible");
                continue;
            }
            ParsedBlock parsed;
            c.check(ParseSelectors(dst, &parsed, false), "counterexample output parses");
            for (int y = 0; y < 4; ++y) {
                for (int x = 0; x < 4; ++x) {
                    if (IsAnchor(2, parsed.partition, x, y)) {
                        c.check(parsed.selectors[y * 4 + x] < (1 << (parsed.primary_bits - 1)),
                                "counterexample anchor MSB is cleared");
                    }
                }
            }
            CheckPixels(c, block, op);
        }

        /* Flip analysis: with partition 0 and a selector of 3 on the pixel that
           reaches the anchor, the transform must complement that subset, which
           also flips the decoded pixels back into agreement. Check that the
           output block is genuinely different from a naive copy of the
           selectors (a naive copy would be illegal and decode differently). */
        {
            std::vector<unsigned char> dst(16, 0);
            if (bcdec_bc7_transform(block.data(), dst.data(), BCDEC_ROTATE_90) ==
                BCDEC_TRANSFORM_OK) {
                c.check(dst != block, "a real rearrangement happened");
                std::vector<unsigned char> want = ExpectedPixels(DecodeBlock(block), BCDEC_ROTATE_90);
                c.check(DecodeBlock(dst) == want, "counterexample decodes correctly after the flip");
            }
        }
    }

    /* Every accepted transform, for every mode and partition, must leave all
       output anchors with a clear MSB and correct decoded pixels. */
    for (int mode = 0; mode < 8; ++mode) {
        const int parts = PartitionCount(mode);
        for (int part = 0; part < parts; ++part) {
            std::vector<unsigned char> src =
                MakeBlock(BlockConfig{mode, part, 0, 0, true, true, 101u + part});
            for (int o = 1; o < 8; ++o) {
                bcdec_transform_op op = static_cast<bcdec_transform_op>(o);
                std::vector<unsigned char> dst(16, 0);
                if (bcdec_bc7_transform(src.data(), dst.data(), op) != BCDEC_TRANSFORM_OK) continue;

                /* every anchor of the output must have its MSB clear */
                ParsedBlock parsed;
                bool ok = ParseSelectors(dst, &parsed, false);
                c.check(ok, "output block must parse");
                int max = parsed.primary_bits;
                for (int y = 0; y < 4; ++y) {
                    for (int x = 0; x < 4; ++x) {
                        if (!IsAnchor(mode, parsed.partition, x, y)) continue;
                        c.check(parsed.selectors[y * 4 + x] < (1 << (max - 1)),
                                "anchor selector keeps its MSB clear after transform");
                    }
                }
                /* and the decoded pixels still match */
                CheckPixels(c, src, op);
            }
        }
    }

    /* Mode 4: the two selector streams must not be conflated. Build a block
       whose color and alpha streams differ sharply, then verify each channel
       follows its own stream's permutation. */
    for (int isel = 0; isel < 2; ++isel) {
        BlockConfig cfg;
        cfg.mode = 4;
        cfg.partition = 0;
        cfg.index_selection = isel;
        cfg.random_endpoints = false;
        cfg.nonzero = true;
        cfg.seed = 31u;
        std::vector<unsigned char> src = MakeBlock(cfg);

        std::vector<unsigned char> dst(16, 0);
        c.check(bcdec_bc7_transform(src.data(), dst.data(), BCDEC_ROTATE_90) == BCDEC_TRANSFORM_OK,
                "mode 4 rotate 90 succeeds");
        std::vector<unsigned char> a = DecodeBlock(src);
        std::vector<unsigned char> b = DecodeBlock(dst);
        std::vector<unsigned char> want = ExpectedPixels(a, BCDEC_ROTATE_90);
        c.check(std::memcmp(b.data(), want.data(), 64) == 0,
                "mode 4 color and alpha each follow their own stream");

        /* index selection bit survives */
        c.check(HeaderField(dst, 4 + 1 + 2, 1) == isel, "mode 4 index selection is preserved");

        /* the two streams carry different data, otherwise the check is vacuous */
        ParsedBlock prim, sec;
        c.check(ParseSelectors(src, &prim, false) && ParseSelectors(src, &sec, true),
                "mode 4 has two parseable streams");
        bool differs = false;
        for (int i = 0; i < 16; ++i) if (prim.selectors[i] != sec.selectors[i]) differs = true;
        c.check(differs, "test block really has distinct color and alpha streams");
    }

    /* Mode 5 has two independent streams with different widths (2 and 2 bits);
       mode 6 has a single stream feeding both color and alpha. */
    for (int mode : { 5, 6 }) {
        std::vector<unsigned char> src =
            MakeBlock(BlockConfig{mode, 0, 0, 0, true, true, 73u});
        std::vector<unsigned char> dst(16, 0);
        c.check(bcdec_bc7_transform(src.data(), dst.data(), BCDEC_ANTI_TRANSPOSE) ==
                    BCDEC_TRANSFORM_OK, "single subset transform succeeds");
        std::vector<unsigned char> want = ExpectedPixels(DecodeBlock(src), BCDEC_ANTI_TRANSPOSE);
        c.check(DecodeBlock(dst) == want, "single subset pixels match");
    }

    /* All eight modes must produce legal anchors for every accepted transform. */
    for (int mode = 0; mode < 8; ++mode) {
        for (int part = 0; part < PartitionCount(mode); ++part) {
            std::vector<unsigned char> src =
                MakeBlock(BlockConfig{mode, part, 0, 0, true, true, 211u + part});
            for (int o = 0; o < 8; ++o) {
                std::vector<unsigned char> dst(16, 0x99);
                bcdec_transform_status st =
                    bcdec_bc7_transform(src.data(), dst.data(), static_cast<bcdec_transform_op>(o));
                if (st != BCDEC_TRANSFORM_OK) continue;
                ParsedBlock parsed;
                if (!ParseSelectors(dst, &parsed, false)) {
                    c.check(false, "accepted output must parse");
                    continue;
                }
                for (int y = 0; y < 4; ++y) {
                    for (int x = 0; x < 4; ++x) {
                        if (IsAnchor(mode, parsed.partition, x, y)) {
                            c.check(parsed.selectors[y * 4 + x] < (1 << (parsed.primary_bits - 1)),
                                    "anchor MSB clear");
                        }
                    }
                }
            }
        }
    }
}

