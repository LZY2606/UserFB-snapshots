struct BitWriter {
    std::vector<unsigned char> bytes;
    int pos = 0;
    BitWriter() : bytes(16, 0) {}
    void put(unsigned value, int count) {
        for (int i = 0; i < count; ++i, ++pos) {
            if ((value >> i) & 1u) {
                bytes[pos >> 3] = static_cast<unsigned char>(bytes[pos >> 3] | (1u << (pos & 7)));
            }
        }
    }
};

const int kSubsets[8]   = { 3, 2, 3, 2, 1, 1, 1, 2 };
const int kRgbBits[8]   = { 4, 6, 5, 7, 5, 7, 7, 5 };
const int kAlphaBits[8] = { 0, 0, 0, 0, 6, 8, 7, 5 };
const int kHasPBits[8]  = { 1, 1, 0, 1, 0, 0, 1, 1 };
const int kPrimary[8]   = { 3, 3, 2, 2, 2, 2, 4, 2 };
const int kSecondary[8] = { 0, 0, 0, 0, 3, 2, 0, 0 };

int SubsetsOf(int mode) { return kSubsets[mode]; }
int PartitionCount(int mode) { return SubsetsOf(mode) == 1 ? 1 : (mode == 0 ? 16 : 64); }
bool IsAnchor(int mode, int partition, int x, int y) {
    if (SubsetsOf(mode) == 1) return x == 0 && y == 0;
    return (kStdPartitionSets[SubsetsOf(mode) - 2][partition][y][x] & 0x80) != 0;
}

struct Lcg {
    std::uint32_t state;
    explicit Lcg(std::uint32_t s) : state(s ? s : 1u) {}
    std::uint32_t next() { state = state * 1664525u + 1013904223u; return state >> 16; }
    int bits(int n) { return static_cast<int>(next() & ((1u << n) - 1u)); }
};

struct BlockConfig {
    int mode = 0;
    int partition = 0;
    int rotation = 0;
    int index_selection = 0;
    bool random_endpoints = false;
    bool nonzero = false;
    std::uint32_t seed = 1u;
};

/* Produces a structurally valid BC7 block with the requested header fields. */
std::vector<unsigned char> MakeBlock(const BlockConfig& cfg) {
    BitWriter w;
    Lcg rng(cfg.seed);
    const int subsets = SubsetsOf(cfg.mode);
    const int endpoints = subsets * 2;
    const int endpoint_count = cfg.nonzero ? 2 : 1;

    w.put(1u << cfg.mode, cfg.mode + 1);
    if (subsets > 1) w.put(cfg.partition, cfg.mode == 0 ? 4 : 6);
    if (cfg.mode == 4 || cfg.mode == 5) {
        w.put(cfg.rotation, 2);
        if (cfg.mode == 4) w.put(cfg.index_selection, 1);
    }
    for (int c = 0; c < 3; ++c) {
        for (int e = 0; e < endpoints; ++e) {
            int bits = kRgbBits[cfg.mode];
            int v = cfg.random_endpoints
                        ? rng.bits(bits)
                        : static_cast<int>((cfg.seed * 37u + c * 11u + e * 23u + endpoint_count * 5u)
                                           & ((1u << bits) - 1u));
            w.put(static_cast<unsigned>(v), bits);
        }
    }
    if (kAlphaBits[cfg.mode] > 0) {
        for (int e = 0; e < endpoints; ++e) {
            int bits = kAlphaBits[cfg.mode];
            int v = cfg.random_endpoints
                        ? rng.bits(bits)
                        : static_cast<int>((cfg.seed * 53u + e * 29u + endpoint_count * 3u)
                                           & ((1u << bits) - 1u));
            w.put(static_cast<unsigned>(v), bits);
        }
    }
    if (cfg.mode == 1) {
        for (int s = 0; s < subsets; ++s) w.put((cfg.seed + s) & 1u, 1);
    } else if (kHasPBits[cfg.mode]) {
        for (int e = 0; e < endpoints; ++e) w.put((cfg.seed + e) & 1u, 1);
    }

    const int primary = kPrimary[cfg.mode];
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 4; ++x) {
            int bits = primary - (IsAnchor(cfg.mode, cfg.partition, x, y) ? 1 : 0);
            int v = cfg.random_endpoints
                        ? rng.bits(bits)
                        : static_cast<int>((x * 4 + y + cfg.seed) & ((1 << bits) - 1));
            w.put(static_cast<unsigned>(v), bits);
        }
    }
    const int secondary = kSecondary[cfg.mode];
    if (secondary > 0) {
        for (int y = 0; y < 4; ++y) {
            for (int x = 0; x < 4; ++x) {
                int bits = secondary - (IsAnchor(cfg.mode, cfg.partition, x, y) ? 1 : 0);
                int v = cfg.random_endpoints
                            ? rng.bits(bits)
                            : static_cast<int>((x * 3 + y * 7 + cfg.seed) & ((1 << bits) - 1));
                w.put(static_cast<unsigned>(v), bits);
            }
        }
    }
    return w.bytes;
}

void SourceToDest(bcdec_transform_op op, int x, int y, int* dx, int* dy) {
    switch (op) {
        case BCDEC_IDENTITY:       *dx = x;     *dy = y;     break;
        case BCDEC_ROTATE_90:      *dx = 3 - y; *dy = x;     break;
        case BCDEC_ROTATE_180:     *dx = 3 - x; *dy = 3 - y; break;
        case BCDEC_ROTATE_270:     *dx = y;     *dy = 3 - x; break;
        case BCDEC_FLIP_X:         *dx = 3 - x; *dy = y;     break;
        case BCDEC_FLIP_Y:         *dx = x;     *dy = 3 - y; break;
        case BCDEC_TRANSPOSE:      *dx = y;     *dy = x;     break;
        case BCDEC_ANTI_TRANSPOSE: *dx = 3 - y; *dy = 3 - x; break;
        default:                   *dx = -1;    *dy = -1;    break;
    }
}

/* Reference permutation in destination space: out(SourceToDest(s)) = in(s). */
std::vector<unsigned char> ExpectedPixels(const std::vector<unsigned char>& pixels,
                                          bcdec_transform_op op) {
    std::vector<unsigned char> out(64, 0);
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 4; ++x) {
            int dx, dy;
            SourceToDest(op, x, y, &dx, &dy);
            std::memcpy(&out[(dy * 4 + dx) * 4], &pixels[(y * 4 + x) * 4], 4);
        }
    }
    return out;
}

std::vector<unsigned char> DecodeBlock(const std::vector<unsigned char>& block) {
    std::vector<unsigned char> pixels(64, 0);
    bcdec_bc7(block.data(), pixels.data(), 16);
    return pixels;
}

std::vector<unsigned char> RunTransform(const std::vector<unsigned char>& src,
                                        bcdec_transform_op op) {
    std::vector<unsigned char> dst(16, 0);
    bcdec_transform_status st = bcdec_bc7_transform(src.data(), dst.data(), op);
    if (st != BCDEC_TRANSFORM_OK) dst.assign(16, 0xEE);
    return dst;
}

/* Independent structural check: does the permutation of `labels` fit any
   standard partition of this mode? Returns the lowest such partition index or
   -1. Mirrors only the definition, never the implementation. */
int StructurallyRepresentable(int mode, int partition, bcdec_transform_op op) {
    const int subsets = SubsetsOf(mode);
    const int limit = PartitionCount(mode);
    int label[4][4];
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 4; ++x) {
            label[y][x] = kStdPartitionSets[subsets - 2][partition][y][x] & 0x03;
        }
    }
    /* inverse permutation: source coordinate of destination (x,y) */
    int inv[4][4][2];
    for (int y = 0; y < 4; ++y) {
        for (int x = 0; x < 4; ++x) {
            int sx = 0, sy = 0;
            for (int yy = 0; yy < 4; ++yy) {
                for (int xx = 0; xx < 4; ++xx) {
                    int dx, dy;
                    SourceToDest(op, xx, yy, &dx, &dy);
                    if (dx == x && dy == y) { sx = xx; sy = yy; }
                }
            }
            inv[y][x][0] = sx;
            inv[y][x][1] = sy;
        }
    }

    for (int candidate = 0; candidate < limit; ++candidate) {
        int map[3] = { -1, -1, -1 };
        bool used[3] = { false, false, false };
        bool ok = true;
        for (int y = 0; y < 4 && ok; ++y) {
            for (int x = 0; x < 4 && ok; ++x) {
                int t = kStdPartitionSets[subsets - 2][candidate][y][x] & 0x03;
                int s = label[inv[y][x][1]][inv[y][x][0]];
                if (map[t] < 0) {
                    if (used[s]) { ok = false; break; }
                    map[t] = s;
                    used[s] = true;
                } else if (map[t] != s) {
                    ok = false;
                }
            }
        }
        if (!ok) continue;
        bool bijective = true;
        for (int s = 0; s < subsets; ++s) if (!used[s]) bijective = false;
        if (bijective) return candidate;
    }
    return -1;
}

/* Check the full 4x4 pixel equivalence for one block/op pair, and return the
   transform status. */
bcdec_transform_status CheckPixels(Case& c, const std::vector<unsigned char>& src,
                                   bcdec_transform_op op) {
    std::vector<unsigned char> dst(16, 0);
    bcdec_transform_status st = bcdec_bc7_transform(src.data(), dst.data(), op);
    if (st != BCDEC_TRANSFORM_OK) return st;

    std::vector<unsigned char> before = DecodeBlock(src);
    std::vector<unsigned char> after = DecodeBlock(dst);
    std::vector<unsigned char> want = ExpectedPixels(before, op);
    c.check(std::memcmp(after.data(), want.data(), 64) == 0,
            "decoded transform does not match the independent pixel permutation");

    /* anchor MSB rule: every fix-up anchor selector must have a zero MSB */
    int mode = 0;
    while (mode < 8 && (src[0] & (1u << mode)) == 0) ++mode;
    if (SubsetsOf(mode) > 1) {
        int partition = 0;
        int bit = mode + 1;
        int nbits = mode == 0 ? 4 : 6;
        for (int i = 0; i < nbits; ++i) {
            if ((dst[(bit + i) >> 3] >> ((bit + i) & 7)) & 1) partition |= 1 << i;
        }
        int ibits = kPrimary[mode];
        int pos = mode + 1 + nbits;
        pos += 3 * 2 * kRgbBits[mode] + 2 * kAlphaBits[mode];
        if (mode == 1) pos += SubsetsOf(mode);
        else if (kHasPBits[mode]) pos += 2 * SubsetsOf(mode);
        for (int y = 0; y < 4; ++y) {
            for (int x = 0; x < 4; ++x) {
                int bits = ibits - (IsAnchor(mode, partition, x, y) ? 1 : 0);
                int value = 0;
                for (int i = 0; i < bits; ++i) {
                    if ((dst[(pos + i) >> 3] >> ((pos + i) & 7)) & 1) value |= 1 << i;
                }
                pos += bits;
                if (IsAnchor(mode, partition, x, y)) {
                    c.check((value >> (ibits - 1)) == 0, "anchor selector MSB must be zero");
                }
            }
        }
    }
    return st;
}

int HeaderField(const std::vector<unsigned char>& block, int pos, int count) {
    int v = 0;
    for (int i = 0; i < count; ++i) {
        if ((block[(pos + i) >> 3] >> ((pos + i) & 7)) & 1) v |= 1 << i;
    }
    return v;
}

