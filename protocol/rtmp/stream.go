func (s *Stream) TransStart() {
	s.isStart = true
	var p av.Packet

	log.Debugf("TransStart: %v", s.info)

	s.StartStaticPush()

	for {
		if !s.isStart {
			s.closeInter()
			return
		}
		err := s.r.Read(&p)
		if err != nil {
			s.closeInter()
			s.isStart = false
			return
		}

		if s.IsSendStaticPush() {
			s.SendStaticPush(p)
		}

		s.writePacket(p)
	}
}

// writePacket appends one published packet to the cache and delivers it to all
// subscribers, seeding subscribers that have not been initialised yet.
func (s *Stream) writePacket(p av.Packet) {
	s.cache.Write(p)

	s.ws.Range(func(key, val interface{}) bool {
		v := val.(*PackWriterCloser)
		var err error
		if !v.init {
			//log.Debugf("cache.send: %v", v.w.Info())
			if err = s.sendCache(v); err != nil {
				// A playback range error is reported before any media is
				// written and does not affect the publisher or other writers.
				if err == cache.ErrPlaybackRange {
					log.Infof("[%s] playback start out of retained cache range", v.w.Info())
				} else {
					log.Debugf("[%s] send cache packet error: %v, remove", v.w.Info(), err)
				}
				s.ws.Delete(key)
				v.w.Close(err)
				return true
			}
		} else {
			//writeType := reflect.TypeOf(v.w)
			//log.Debugf("w.Write: type=%v, %v", writeType, v.w.Info())
			if err = s.writeLive(v, p); err != nil {
				log.Debugf("[%s] write packet error: %v, remove", v.w.Info(), err)
				s.ws.Delete(key)
			}
		}
		return true
	})
}

func (s *Stream) TransStop() {
	log.Debugf("TransStop: %s", s.info.Key)

	if s.isStart && s.r != nil {
		s.r.Close(fmt.Errorf("stop old"))
	}

	s.isStart = false
}

func (s *Stream) CheckAlive() (n int) {
	if s.r != nil && s.isStart {
		if s.r.Alive() {
			n++
		} else {
			s.r.Close(fmt.Errorf("read timeout"))
		}
	}

	s.ws.Range(func(key, val interface{}) bool {
		v := val.(*PackWriterCloser)
		if v.w != nil {
			//Alive from RWBaser, check last frame now - timestamp, if > timeout then Remove it
			if !v.w.Alive() {
				log.Infof("write timeout remove")
				s.ws.Delete(key)
				v.w.Close(fmt.Errorf("write timeout"))
				return true
			}
			n++
		}
		return true
	})

	return
}

func (s *Stream) closeInter() {
	if s.r != nil {
		s.StopStaticPush()
		log.Debugf("[%v] publisher closed", s.r.Info())
	}

	s.ws.Range(func(key, val interface{}) bool {
		v := val.(*PackWriterCloser)
		if v.w != nil {
			v.w.Close(fmt.Errorf("closed"))
			if v.w.Info().IsInterval() {
				s.ws.Delete(key)
				log.Debugf("[%v] player closed and remove\n", v.w.Info())
			}
		}
		return true
	})
}
