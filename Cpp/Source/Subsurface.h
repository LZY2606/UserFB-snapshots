#pragma once
//
// Non-local subsurface diffusion material (CPU path only).
//
// Model
// -----
// Per color channel c, the radial area kernel is a mixture of two 2D Gaussians
// with standard deviations d_c and 3*d_c:
//
//   S_d(r) = 0.5*exp(-r^2/(2 d^2))/(2 pi d^2) + 0.5*exp(-r^2/(18 d^2))/(18 pi d^2)
//
// Exitant radiance at a surface point xo towards the eye is the integral over
// the SAME sphere's surface of
//
//   rho_c * S_{d_c}(|xi - xo|) * E(xi) dA(xi),
//
// where E(xi) is the integral of Li*cos/pi over the outgoing hemisphere at xi.
// No Fresnel, no volumetric random walk, no medium outside the sphere, and the
// kernel is NOT renormalized on the finite sphere. Ordinary emission is still
// accumulated at xo first (handled by the caller in Trace).
//
// Relocation sampling
// -------------------
// Candidate exit points xi are generated by projected-disk sampling: at xo's
// outward normal and a pair of orthogonal tangents, a projection axis is chosen
// with probabilities 1/2, 1/4, 1/4. A color channel is chosen uniformly, then
// scale d_c or 3*d_c uniformly, giving a 2D Gaussian on the disk (Rayleigh
// radial distribution, uniform azimuth). The infinite line through the disk
// point parallel to the axis is intersected with the CURRENT sphere only; one
// of the two intersections is picked uniformly. A miss is a zero-contribution
// event (no resampling); tangency is a zero-measure event. The auxiliary line
// is not a transport ray: other spheres neither receive the jump nor cull it.
//
// The PDF returned by SubsurfaceRelocationPdf is the full mixture density per
// unit true sphere surface area: sum over the 3 axes and 3 channels of
// axisProb * channelProb * S_d(projected distance) * |n(xi).axis| / N_axis,
// where N_axis is the candidate count of THAT axis' own line through xi
// (recomputed per axis, not reused from the sampled axis).
//
// Data ownership
// --------------
// The sampling/PDF functions below are pure: all inputs are caller-owned and
// nothing is stored. The scene-control functions (SubsurfaceSetScene etc.)
// COPY the passed data into renderer-owned storage; the caller keeps ownership
// of the passed arrays and may reuse or free them immediately after the call.
// The renderer-owned copy stays valid until the next SubsurfaceSetScene /
// SubsurfaceResetScene call.

#include "Maths.h"

// Per-sphere subsurface parameters: RGB albedo rho and three positive
// diffusion scales d (one per color channel).
struct SubsurfaceParams
{
    float3 rho;
    float3 d;
};

// True when all components are finite, rho >= 0 and d > 0.
bool SubsurfaceParamsValid(const SubsurfaceParams& p);

// The radial area kernel S_d(r) for one channel.
float SubsurfaceKernel(float d, float r);

// Deterministic tangent frame for an outward unit normal. Public so callers
// (and tests) can reproduce the projection axes: axis0 = normal (prob 1/2),
// axis1 = t1 (prob 1/4), axis2 = t2 (prob 1/4).
void SubsurfaceFrame(const float3& outwardNormal, float3& outT1, float3& outT2);

// Result of one relocation sample.
struct SubsurfaceSample
{
    bool valid;     // false: line missed the sphere -> zero contribution (no resample)
    float3 pos;     // candidate exit position xi on the same sphere
    float3 normal;  // outward normal at xi
    int sphereId;   // sphere the candidate lives on (always the source sphere)
};

// Draw a relocated exit point on the same sphere. Consumes random numbers from
// rngState (project's xorshift stream). sphereCenter/sphereRadius describe the
// sphere xo lives on; xo/outwardNormal is the exit point being relocated.
SubsurfaceSample SubsurfaceSampleRelocation(
    const float3& sphereCenter, float sphereRadius, int sphereId,
    const SubsurfaceParams& params,
    const float3& xo, const float3& outwardNormal,
    uint32_t& rngState);

// Full mixture density of candidate xi, per unit true sphere surface area.
float SubsurfaceRelocationPdf(
    const float3& sphereCenter, float sphereRadius,
    const SubsurfaceParams& params,
    const float3& xo, const float3& outwardNormal,
    const float3& xi);

// Per-channel non-local transport weight rho_c * S_{d_c}(|xi-xo|) / areaPdf.
// Returns 0 when areaPdf is not positive.
float3 SubsurfaceWeight(const SubsurfaceParams& params, const float3& xo, const float3& xi, float areaPdf);


// ---- CPU scene control, constant sky and single-ray radiance entry ----
// (implemented in Test.cpp on top of the production tracer)

struct SubsurfaceSceneSphere
{
    float center[3];
    float radius;
};

struct SubsurfaceSceneMaterial
{
    int type; // 0=Lambert, 1=Metal, 2=Dielectric, 3=Subsurface
    float albedo[3];
    float emissive[3];
    float roughness;
    float ri;
};

// Replaces the whole CPU scene. All arrays are copied into renderer-owned
// storage before the call returns (caller keeps ownership of the arrays).
// subsurfaceParams is per-sphere and is only read for spheres whose material
// type is 3 (Subsurface); it may be null when no such material exists.
// Returns false and leaves the current scene untouched when any parameter is
// invalid (non-finite values, non-positive radius, non-positive diffusion
// scale, unknown material type, ...).
bool SubsurfaceSetScene(const SubsurfaceSceneSphere* spheres,
                        const SubsurfaceSceneMaterial* materials,
                        const SubsurfaceParams* subsurfaceParams,
                        int count);

// Restores the built-in default scene.
void SubsurfaceResetScene();

// Constant sky radiance for rays that miss everything / default gradient sky.
void SubsurfaceSetSky(float r, float g, float b);
void SubsurfaceResetSky();

// Camera used by the next UpdateTest call (vfov in degrees).
void SubsurfaceSetCamera(const float* lookFrom, const float* lookAt, const float* vUp,
                         float vfovDeg, float aperture, float focusDist);

// Traces a single ray through the current CPU scene and returns its radiance.
// dir must be normalized. rngState drives all sampling; inoutRayCount
// accumulates the number of rays traced.
float3 SubsurfaceTraceRay(const float3& orig, const float3& dir, uint32_t& rngState, int& inoutRayCount);
