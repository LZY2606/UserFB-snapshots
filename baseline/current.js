import assert from 'node:assert/strict';
import Scene from '../src/Scene';
import Node from '../src/Node';
import Mesh from '../src/Mesh';
import Skeleton from '../src/Skeleton';
import Joint from '../src/Joint';
const root = new Node({name:'actor'});
const bone = new Node({name:'hip'}); root.add(bone);
const skeleton = new Skeleton({name:'rig', relativeRootNode:root});
skeleton.joints.push(new Joint({name:'hip',index:0,node:bone}));
root.update(); skeleton.updateJointMatrices(); skeleton.update();
const a = new Mesh({name:'body',skeleton,joints:[0]});
const b = new Mesh({name:'coat',skeleton,joints:[0]}); root.add(a); root.add(b);
assert.equal(a.skeleton,b.skeleton);
const cloned = new Scene().cloneNode(root);
const parts = cloned.children();
assert.notEqual(parts[1].skeleton,parts[2].skeleton);
assert.equal(parts[1].skeleton.joints[0].node,parts[0]);
assert.equal(parts[1].skeleton.relativeRootNode,null);
assert.notEqual(parts[1].skeleton._skinMatricesArray,skeleton._skinMatricesArray);
parts[0].position.x=3; cloned.update(); parts[1].skeleton.update();
assert.equal(parts[1].skeleton._skinMatricesArray[12],3);
assert.equal(skeleton._skinMatricesArray[12],0);
