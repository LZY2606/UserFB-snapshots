import assert from 'node:assert/strict';
import { WebGLRenderer } from '../src/webgl/WebGLRenderer.js';
import { Mesh } from '../src/scenes/Mesh.js';
import { Geometry } from '../src/resources/geometries/Geometry.js';
import { Attribute } from '../src/resources/geometries/Attribute.js';
import { Buffer } from '../src/resources/geometries/Buffer.js';
import { Vector3 } from '../src/math/Vector3.js';
const attr = x => new Attribute(new Buffer(new Float32Array([x,0,0]),3));
const g = new Geometry(); g.addAttribute('a_Position',attr(0));
g.morphAttributes.position = Array.from({length:9},()=>attr(1));
const mesh = new Mesh(g,null); mesh.morphTargetInfluences = Array(9).fill(0.25);
let weights;
const program = {getUniforms:()=>({set:(name,w)=>{weights=Array.from(w);}})};
WebGLRenderer.prototype._updateMorphtargets.call({},mesh,g,program);
const cpu = mesh.getVertexPosition(0,new Vector3()).x;
let supplied = 0;
for(let i=0;i<8;i++) supplied += g.getAttribute('morphTarget'+i).buffer.array[0]*weights[i];
assert.equal(cpu,2.25); assert.equal(supplied,2);
mesh.morphTargetInfluences = [-0.5,0,0,0,0,0,0,0,0];
WebGLRenderer.prototype._updateMorphtargets.call({},mesh,g,program);
assert.equal(mesh.getVertexPosition(0,new Vector3()).x,-0.5);
assert.equal(weights.reduce((a,b)=>a+b,0),0);
console.log('T3D_CURRENT_OK cpu=2.25 shader8=2 negativeCPU=-0.5 uniformSum=0');
