import assert from 'node:assert/strict';
import { Structure3D } from '../src/core/Structure3D.js';
import { Chain3D } from '../src/core/Chain3D.js';
import { Bone3D } from '../src/core/Bone3D.js';
import { V3 } from '../src/math/V3.js';
const host = new Chain3D();
host.addBone(new Bone3D(new V3(),new V3(0,0,2)));
const template = new Chain3D();
template.addBone(new Bone3D(new V3(),new V3(0,0,1)));
template.addConsecutiveRotorConstrainedBone(new V3(0,0,1),1,0);
template.setRotorBaseboneConstraint('local',new V3(0,0,1),0);
const ht = new V3(2,0,0), ct = new V3(4,0,0);
const structure = new Structure3D();
structure.add(host,ht,false); structure.connectChain(template,0,0,'end',ct,false);
const near = (a,b) => assert.ok(a.distanceTo(b)<1e-6,JSON.stringify({a,b}));
structure.update(); const child = structure.getChain(1);
near(host.bones[0].end,new V3(2,0,0));
near(child.bones[0].start,host.bones[0].end); near(child.bones[1].end,ct);
ht.set(0,0,2); ct.set(0,0,4); structure.update();
near(child.bones[0].start,host.bones[0].end); near(child.bones[1].end,ct);
for(const b of child.bones) assert.ok(Math.abs(b.start.distanceTo(b.end)-1)<1e-6);
near(template.bones[0].start,new V3()); near(template.bones[1].end,new V3(0,0,2));
console.log('FULLIK_CURRENT_OK connected=2 rotatedEndZ=4 lengths=1 templateUnchanged=1');
