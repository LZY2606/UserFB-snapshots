/*
Regression test for integer weighted channel mixing in ma_channel_converter and ma_data_converter.

The mixing contract under test is: for every output sample, multiply each signed input sample by
its already-quantized fixed-point weight, sum every product into one accumulator, apply a single
round toward negative infinity, and only then clip to the output format's range. Expected values
are generated by independent reference models in this file - never by running data through the
converter and converting floating point back.

Channel maps are supplied explicitly so equal-channel-count cases still take the weights path
instead of the passthrough/shuffle fast paths (those keep their old, separate behavior).

The same source is compiled two ways:
  1. Against the single-header build (MINIAUDIO_IMPLEMENTATION defined here).
  2. Against extras/miniaudio_split (MIX_TEST_SPLIT defined, split miniaudio.c compiled separately).
*/
#if defined(MIX_TEST_SPLIT)
#include "miniaudio.h"
#else
#define MINIAUDIO_IMPLEMENTATION
#include "miniaudio.h"
#endif

#include <stdio.h>
#include <stdlib.h>
#include <stdarg.h>
#include <string.h>

#define FIXED_SHIFT 12  /* MA_CHANNEL_CONVERTER_FIXED_POINT_SHIFT; that macro lives in the
                           implementation section and is therefore not visible to split-build
                           consumers. The single-header build below asserts the two still agree. */
#if !defined(MIX_TEST_SPLIT)
#if MA_CHANNEL_CONVERTER_FIXED_POINT_SHIFT != FIXED_SHIFT
#error "Test assumption broken: MA_CHANNEL_CONVERTER_FIXED_POINT_SHIFT is no longer 12."
#endif
#endif
#define FIXED_ONE   (1 << FIXED_SHIFT)
#define MAX_IN      4
#define MAX_OUT     2
#define MAX_FRAMES  6
#define GUARD_SIZE  8
#define GUARD_BYTE  0xA5

/* Symbolic sample values resolved per format so endpoint cases stay at the real full-scale values. */
#define TOK_MAX  (-100)
#define TOK_MIN  (-101)
#define TOK_NMAX (-102)

static int g_failures = 0;

static void fail(const char* fmt, ...)
{
    va_list args;
    va_start(args, fmt);
    printf("FAIL: ");
    vprintf(fmt, args);
    printf("\n");
    va_end(args);
    g_failures += 1;
}

typedef struct
{
    ma_format id;
    const char* name;
    int bytesPerSample;
    ma_int64 minValue;
    ma_int64 maxValue;
} fmt_def;

static const fmt_def g_formats[] =
{
    { ma_format_u8,  "u8",  1, -128,      127      },
    { ma_format_s16, "s16", 2, -32768,    32767    },
    { ma_format_s24, "s24", 3, -8388608,  8388607  },
    { ma_format_s32, "s32", 4, -2147483647LL - 1, 2147483647LL }
};
#define FORMAT_COUNT (int)(sizeof(g_formats)/sizeof(g_formats[0]))

/* Distinct positions on both sides: equal channel counts therefore cannot be a shuffle/passthrough. */
static ma_channel g_mapIn2[MAX_IN] = { MA_CHANNEL_FRONT_LEFT,  MA_CHANNEL_FRONT_RIGHT, MA_CHANNEL_BACK_LEFT,  MA_CHANNEL_BACK_RIGHT };
static ma_channel g_mapIn3[3]      = { MA_CHANNEL_FRONT_LEFT,  MA_CHANNEL_FRONT_RIGHT, MA_CHANNEL_FRONT_CENTER };
static ma_channel g_mapOut2[2]     = { MA_CHANNEL_SIDE_LEFT,   MA_CHANNEL_SIDE_RIGHT };

typedef struct
{
    const char* name;
    unsigned channelsIn;
    ma_int64 in[MAX_IN];      /* Signed values, possibly symbolic TOK_* or clamped per format. */
    float weight[MAX_IN];     /* Weights for output channel 0; channel 1 always uses weight 0. */
} mix_case;

static const mix_case g_cases[] =
{
    /* The reported bug: equal-weight contributions that cancel must net out before clipping. */
    { "cancellation",      3, { 30000, 30000, -30000 }, { 1.0f, 1.0f, 1.0f } },

    /* Negative remainder: floor(-1365 / 4096) is -1, truncation toward zero would give 0. */
    { "neg_remainder",     2, { -1, 0 },                { 1.0f/3.0f, 1.0f } },

    /* Rounding each product first gives (1*2048)>>12 + (-1*2048)>>12 = 0 + -1 = -1; the real sum is 0. */
    { "round_per_product", 2, { 1, -1 },                { 0.5f, 0.5f } },

    /* Clipping after every add saturates the running total and can never recover; the full sum is 0. */
    { "clamp_per_add",     4, { TOK_MAX, TOK_MAX, TOK_NMAX, TOK_NMAX }, { 1.0f, 1.0f, 1.0f, 1.0f } },

    /* Several near-full-scale contributions stacked together, ending in range. */
    { "near_full_stack",   4, { TOK_MAX, TOK_MAX, TOK_NMAX, 0 },        { 0.5f, 0.5f, 0.5f, 0.5f } },

    /* Zero weights silence everything regardless of the input magnitudes. */
    { "zero_weights",      3, { 30000, -30000, 30000 },  { 0.0f, 0.0f, 0.0f } },

    /* Both endpoints in one frame. */
    { "endpoints_sum",     2, { TOK_MAX, TOK_MIN },      { 1.0f, 1.0f } },
    { "endpoint_max",      2, { TOK_MAX, TOK_MIN },      { 1.0f, 0.0f } },
    { "endpoint_min",      2, { TOK_MAX, TOK_MIN },      { 0.0f, 1.0f } },

    /* u8 silence is the signed zero sample (byte 128 on the integer mixing paths). */
    { "u8_silence",        2, { 0, 0 },                  { 1.0f, 1.0f } }
};
#define CASE_COUNT (int)(sizeof(g_cases)/sizeof(g_cases[0]))

static ma_int64 clamp64(ma_int64 x, ma_int64 lo, ma_int64 hi)
{
    if (x < lo) return lo;
    if (x > hi) return hi;
    return x;
}

static ma_int64 resolve_token(ma_int64 v, const fmt_def* f)
{
    if (v == TOK_MAX)  return f->maxValue;
    if (v == TOK_MIN)  return f->minValue;
    if (v == TOK_NMAX) return -f->maxValue;
    return clamp64(v, f->minValue, f->maxValue);
}

/* Mirrors ma_channel_converter_float_to_fixed: (ma_int32)(x * 4096). */
static ma_int32 quantize_weight(float w)
{
    return (ma_int32)(w * (float)(1 << FIXED_SHIFT));
}

/* Independent wide-integer reference: full sum, one floor rounding, then clip. */
static ma_int64 ref_mix(const ma_int64* in, const ma_int32* qw, unsigned n, const fmt_def* f)
{
    ma_int64 acc = 0;
    unsigned i;
    for (i = 0; i < n; ++i) {
        acc += in[i] * (ma_int64)qw[i];
    }

    return clamp64(acc >> FIXED_SHIFT, f->minValue, f->maxValue);
}

/* Deliberately wrong model #1: round every product before summing. */
static ma_int64 bad_round_per_product(const ma_int64* in, const ma_int32* qw, unsigned n, const fmt_def* f)
{
    ma_int64 acc = 0;
    unsigned i;
    for (i = 0; i < n; ++i) {
        acc += (in[i] * (ma_int64)qw[i]) >> FIXED_SHIFT;
    }

    return clamp64(acc, f->minValue, f->maxValue);
}

/* Deliberately wrong model #2: clip after every addition (and round each product like the old code did). */
static ma_int64 bad_clamp_per_add(const ma_int64* in, const ma_int32* qw, unsigned n, const fmt_def* f)
{
    ma_int64 acc = 0;
    unsigned i;
    for (i = 0; i < n; ++i) {
        ma_int64 term = (in[i] * (ma_int64)qw[i]) >> FIXED_SHIFT;
        acc = clamp64(acc + term, f->minValue, f->maxValue);
    }

    return acc;
}

/* Signed sample access for every supported integer format (u8 handled with its 128 offset). */
static ma_int64 read_sample(const fmt_def* f, const ma_uint8* p)
{
    switch (f->id) {
        case ma_format_u8:  return (ma_int64)p[0] - 128;
        case ma_format_s16: return (ma_int64)*(const ma_int16*)p;
        case ma_format_s32: return (ma_int64)*(const ma_int32*)p;
        case ma_format_s24:
        {
            ma_uint32 u = (ma_uint32)p[0] | ((ma_uint32)p[1] << 8) | ((ma_uint32)p[2] << 16);
            return (ma_int64)((ma_int32)(u << 8) >> 8);  /* Sign-extend the 24-bit value, matching the library's helper. */
        }
        default: return 0;
    }
}

static void write_sample(const fmt_def* f, ma_uint8* p, ma_int64 signedValue)
{
    ma_int64 v = clamp64(signedValue, f->minValue, f->maxValue);
    switch (f->id) {
        case ma_format_u8:  p[0] = (ma_uint8)(v + 128); break;
        case ma_format_s16: *(ma_int16*)p = (ma_int16)v; break;
        case ma_format_s32: *(ma_int32*)p = (ma_int32)v; break;
        case ma_format_s24:
            p[0] = (ma_uint8)(v & 0xFF);
            p[1] = (ma_uint8)((v >> 8) & 0xFF);
            p[2] = (ma_uint8)((v >> 16) & 0xFF);
            break;
        default: break;
    }
}

/* Preallocated converter heap. The library aligns its internal layout to 8 bytes, so the base
   address must be at least 8-byte aligned (a bare ma_uint8 array would only guarantee 1). */
static ma_uint64 g_heap64[(128 * 1024) / sizeof(ma_uint64)];
#define g_heap ((ma_uint8*)g_heap64)

static void fill_guards(ma_uint8* buf, size_t total)
{
    memset(buf, GUARD_BYTE, total);
}

static int check_guards(const char* tag, const ma_uint8* buf, size_t total)
{
    size_t i;
    for (i = 0; i < GUARD_SIZE; ++i) {
        if (buf[i] != GUARD_BYTE || buf[total - 1 - i] != GUARD_BYTE) {
            fail("%s: sentinel byte corrupted", tag);
            return 0;
        }
    }
    return 1;
}

static void build_case_frame(const mix_case* c, const fmt_def* f, ma_int64* outSigned, ma_int32* outQW, float* weightsF)
{
    unsigned i;
    for (i = 0; i < c->channelsIn; ++i) {
        outSigned[i] = resolve_token(c->in[i], f);
        outQW[i] = quantize_weight(c->weight[i]);
        weightsF[i*2 + 0] = c->weight[i];
        weightsF[i*2 + 1] = 0.0f;
    }
}

/*
Independent model of a data-converter pipeline whose mid format is f32. This only applies when the
library really does pick f32 as the mid format (u8/s24/s32 same-rate pipelines). The formulas below
reproduce the library's no-dither integer<->f32 PCM conversions and its float channel mixing using
only this translation unit; the integer endpoints are still compared as integers.
*/
static float ref_int_to_f32(ma_format fmt, ma_int64 signedValue)
{
    switch (fmt) {
        case ma_format_u8:  return (float)(int)(signedValue + 128) * 0.00784313725490196078f - 1.0f;
        case ma_format_s16: return (float)(ma_int16)signedValue * 0.000030517578125f;
        case ma_format_s24: return (float)(ma_int32)signedValue * 0.00000011920928955078125f;
        case ma_format_s32: return (float)((double)(ma_int32)signedValue / 2147483648.0);
        default: return 0.0f;
    }
}

static ma_int64 ref_f32_to_int(ma_format fmt, float x)
{
    switch (fmt) {
        case ma_format_u8:
        {
            float c = (x < -1.0f) ? -1.0f : ((x > 1.0f) ? 1.0f : x);
            c = (c + 1.0f) * 127.5f;
            return (ma_int64)(ma_uint8)c - 128;
        }
        case ma_format_s16:
        {
            float c = (x < -1.0f) ? -1.0f : ((x > 1.0f) ? 1.0f : x);
            return (ma_int16)(c * 32767.0f);
        }
        case ma_format_s24:
        {
            float c = (x < -1.0f) ? -1.0f : ((x > 1.0f) ? 1.0f : x);
            return (ma_int32)(c * 8388607.0f);
        }
        case ma_format_s32:
        {
            double c = (x < -1.0f) ? -1.0 : ((x > 1.0f) ? 1.0 : (double)x);
            return (ma_int32)(c * 2147483647.0);
        }
        default: return 0;
    }
}

static ma_int64 ref_f32_mid_mix(const ma_int64* inSigned, unsigned n, const float* weights,
                                ma_format inFmt, ma_format outFmt)
{
    float acc = 0.0f;
    unsigned i;
    for (i = 0; i < n; ++i) {
        acc += ref_int_to_f32(inFmt, inSigned[i]) * weights[i*2 + 0];
    }

    return ref_f32_to_int(outFmt, acc);
}

/* Runs one case through a directly-created ma_channel_converter and checks every angle. */
static void run_channel_converter_case(const mix_case* c, const fmt_def* f)
{
    ma_int64 inSigned[MAX_IN];
    ma_int32 qw[MAX_IN];
    float weightsFlat[MAX_IN * MAX_OUT];
    float* weightPtrs[MAX_IN];
    ma_channel_converter_config cfg;
    ma_channel_converter conv;
    ma_uint8 inBuf[GUARD_SIZE + MAX_FRAMES * MAX_IN * 4 + GUARD_SIZE];
    ma_uint8 outOne[GUARD_SIZE + MAX_FRAMES * MAX_OUT * 4 + GUARD_SIZE];
    ma_uint8 outChunk[GUARD_SIZE + MAX_FRAMES * MAX_OUT * 4 + GUARD_SIZE];
    ma_uint8 outPerm[GUARD_SIZE + MAX_FRAMES * MAX_OUT * 4 + GUARD_SIZE];
    ma_uint8 inPerm[GUARD_SIZE + MAX_FRAMES * MAX_IN * 4 + GUARD_SIZE];
    ma_int64 expectCh0;
    ma_int64 badRound;
    ma_int64 badClamp;
    unsigned i;
    int frame;
    const size_t inFrameBytes  = (size_t)f->bytesPerSample * c->channelsIn;
    const size_t outFrameBytes = (size_t)f->bytesPerSample * MAX_OUT;
    ma_uint8* pIn       = inBuf + GUARD_SIZE;
    ma_uint8* pOutOne   = outOne + GUARD_SIZE;
    ma_uint8* pOutChunk = outChunk + GUARD_SIZE;
    ma_uint8* pOutPerm  = outPerm + GUARD_SIZE;
    ma_uint8* pInPerm   = inPerm + GUARD_SIZE;

    build_case_frame(c, f, inSigned, qw, weightsFlat);
    for (i = 0; i < c->channelsIn; ++i) {
        weightPtrs[i] = &weightsFlat[i*2];
    }

    expectCh0 = ref_mix(inSigned, qw, c->channelsIn, f);
    badRound  = bad_round_per_product(inSigned, qw, c->channelsIn, f);
    badClamp  = bad_clamp_per_add(inSigned, qw, c->channelsIn, f);

    if (strcmp(c->name, "round_per_product") == 0 && badRound == expectCh0) {
        fail("[%s/%s] per-product-rounding case does not actually distinguish the algorithms", f->name, c->name);
    }
    if (strcmp(c->name, "clamp_per_add") == 0 && badClamp == expectCh0) {
        fail("[%s/%s] per-add-clipping case does not actually distinguish the algorithms", f->name, c->name);
    }

    cfg = ma_channel_converter_config_init(f->id, c->channelsIn, g_mapIn2, MAX_OUT, g_mapOut2, ma_channel_mix_mode_custom_weights);
    cfg.ppWeights = weightPtrs;
    if (ma_channel_converter_init_preallocated(&cfg, g_heap, &conv) != MA_SUCCESS) {
        fail("[%s/%s] channel converter init failed", f->name, c->name);
        return;
    }

    /* Input frames (all identical) and the one-shot conversion. */
    fill_guards(inBuf, sizeof(inBuf));
    fill_guards(outOne, sizeof(outOne));
    for (frame = 0; frame < MAX_FRAMES; ++frame) {
        for (i = 0; i < c->channelsIn; ++i) {
            write_sample(f, pIn + frame*inFrameBytes + (size_t)i*f->bytesPerSample, inSigned[i]);
        }
    }

    if (ma_channel_converter_process_pcm_frames(&conv, pOutOne, pIn, MAX_FRAMES) != MA_SUCCESS) {
        fail("[%s/%s] process failed", f->name, c->name);
    }
    check_guards("one-shot output", outOne, sizeof(outOne));
    check_guards("one-shot input", inBuf, sizeof(inBuf));

    for (frame = 0; frame < MAX_FRAMES; ++frame) {
        ma_int64 got0 = read_sample(f, pOutOne + frame*outFrameBytes);
        ma_int64 got1 = read_sample(f, pOutOne + frame*outFrameBytes + f->bytesPerSample);
        if (got0 != expectCh0) {
            fail("[%s/%s] frame %d ch0: got %lld want %lld", f->name, c->name, frame,
                 (long long)got0, (long long)expectCh0);
        }
        if (got1 != 0) {
            fail("[%s/%s] frame %d ch1 (zero weight column): got %lld want 0", f->name, c->name,
                 frame, (long long)got1);
        }
    }

    /* Chunked conversion with unequal chunk sizes must be identical, frame for frame. */
    {
        static const ma_uint32 chunks[] = { 1, 2, 3 };  /* Sums to MAX_FRAMES. */
        ma_uint32 consumed = 0;
        size_t k;
        fill_guards(outChunk, sizeof(outChunk));
        for (k = 0; k < sizeof(chunks)/sizeof(chunks[0]); ++k) {
            ma_result r = ma_channel_converter_process_pcm_frames(&conv,
                pOutChunk + (size_t)consumed*outFrameBytes,
                pIn + (size_t)consumed*inFrameBytes, chunks[k]);
            if (r != MA_SUCCESS) {
                fail("[%s/%s] chunked process failed", f->name, c->name);
            }
            consumed += chunks[k];
        }
        if (consumed != MAX_FRAMES) {
            fail("[%s/%s] chunked consumed %u frames, want %d", f->name, c->name, consumed, MAX_FRAMES);
        }
        check_guards("chunked output", outChunk, sizeof(outChunk));
        if (memcmp(pOutOne, pOutChunk, (size_t)MAX_FRAMES*outFrameBytes) != 0) {
            fail("[%s/%s] chunked output differs from one-shot output", f->name, c->name);
        }
    }

    /* NULL input means silence: existing behavior zeroes the output buffer. This must run while the
       converter's heap allocation is still intact (the permuted converter below reuses the same heap). */
    {
        ma_uint8 nullOut[GUARD_SIZE + MAX_OUT * 4 + GUARD_SIZE];
        ma_uint8* pNullOut = nullOut + GUARD_SIZE;
        fill_guards(nullOut, sizeof(nullOut));
        if (ma_channel_converter_process_pcm_frames(&conv, pNullOut, NULL, 1) != MA_SUCCESS) {
            fail("[%s/%s] NULL-input process failed", f->name, c->name);
        }
        check_guards("null-input output", nullOut, sizeof(nullOut));
        for (i = 0; i < MAX_OUT; ++i) {
            unsigned b;
            for (b = 0; b < (unsigned)f->bytesPerSample; ++b) {
                if (pNullOut[i*f->bytesPerSample + b] != 0) {
                    fail("[%s/%s] NULL input did not produce the documented zeroed output", f->name, c->name);
                }
            }
        }
    }

    /* Permutation: reverse both the input channels and the weight rows; output must be byte-identical. */
    {
        float permWeightsFlat[MAX_IN * MAX_OUT];
        float* permWeightPtrs[MAX_IN];
        ma_channel_converter_config permCfg;
        ma_channel_converter permConv;
        unsigned pi;
        for (pi = 0; pi < c->channelsIn; ++pi) {
            unsigned src = c->channelsIn - 1 - pi;
            permWeightsFlat[pi*2 + 0] = c->weight[src];
            permWeightsFlat[pi*2 + 1] = 0.0f;
            permWeightPtrs[pi] = &permWeightsFlat[pi*2];
        }
        permCfg = ma_channel_converter_config_init(f->id, c->channelsIn, g_mapIn2, MAX_OUT, g_mapOut2, ma_channel_mix_mode_custom_weights);
        permCfg.ppWeights = permWeightPtrs;
        if (ma_channel_converter_init_preallocated(&permCfg, g_heap, &permConv) != MA_SUCCESS) {
            fail("[%s/%s] permuted converter init failed", f->name, c->name);
            ma_channel_converter_uninit(&conv, NULL);
            return;
        }

        fill_guards(inPerm, sizeof(inPerm));
        fill_guards(outPerm, sizeof(outPerm));
        for (frame = 0; frame < MAX_FRAMES; ++frame) {
            for (pi = 0; pi < c->channelsIn; ++pi) {
                unsigned src = c->channelsIn - 1 - pi;
                write_sample(f, pInPerm + frame*inFrameBytes + (size_t)pi*f->bytesPerSample, inSigned[src]);
            }
        }
        if (ma_channel_converter_process_pcm_frames(&permConv, pOutPerm, pInPerm, MAX_FRAMES) != MA_SUCCESS) {
            fail("[%s/%s] permuted process failed", f->name, c->name);
        }
        check_guards("permuted output", outPerm, sizeof(outPerm));
        check_guards("permuted input", inPerm, sizeof(inPerm));
        if (memcmp(pOutOne, pOutPerm, (size_t)MAX_FRAMES*outFrameBytes) != 0) {
            fail("[%s/%s] output changed when inputs and weights were permuted together", f->name, c->name);
        }
        ma_channel_converter_uninit(&permConv, NULL);
    }

    if (strcmp(c->name, "cancellation") == 0) {
        printf("[%s] cancellation output = %lld (per-product-rounding would give %lld, per-add-clipping %lld)\n",
               f->name, (long long)expectCh0, (long long)badRound, (long long)badClamp);
    }

    ma_channel_converter_uninit(&conv, NULL);
}

/* The f32 weights path is intentionally untouched: lock its plain float accumulation behavior. */
static void run_f32_case(void)
{
    const float in[3] = { -0.75f, 0.25f, 0.5f };
    float weightsFlat[3*2] = { 1.0f, 0.0f, 1.0f, 0.0f, 1.0f, 0.0f };
    float* weightPtrs[3] = { &weightsFlat[0], &weightsFlat[2], &weightsFlat[4] };
    ma_channel_converter_config cfg;
    ma_channel_converter conv;
    float out[2] = { 0.0f, 0.0f };  /* The f32 path accumulates with += without clearing, as before. */
    float expect0;
    unsigned i;

    expect0 = 0.0f;
    for (i = 0; i < 3; ++i) {
        expect0 += in[i] * weightsFlat[i*2];
    }

    cfg = ma_channel_converter_config_init(ma_format_f32, 3, g_mapIn3, 2, g_mapOut2, ma_channel_mix_mode_custom_weights);
    cfg.ppWeights = weightPtrs;
    if (ma_channel_converter_init_preallocated(&cfg, g_heap, &conv) != MA_SUCCESS) {
        fail("[f32] init failed");
        return;
    }
    if (ma_channel_converter_process_pcm_frames(&conv, out, in, 1) != MA_SUCCESS) {
        fail("[f32] process failed");
    }
    if (out[0] != expect0 || out[1] != 0.0f) {  /* -0.0f compares equal to 0.0f. */
        fail("[f32] float mixing changed: got %g/%g want %g/0", out[0], out[1], expect0);
    }
    printf("[f32] weighted sum unchanged = %g\n", out[0]);
    ma_channel_converter_uninit(&conv, NULL);
}

/*
Data converter checks. The channel converter inside a data converter runs in the mid format, so the
references are computed in that mid format; information already discarded by the pre/post format
conversions is not expected to come back.
*/
static void make_data_converter(ma_format inFmt, ma_format outFmt, unsigned chIn, unsigned chOut,
                                float* weightsFlat, ma_data_converter* dc)
{
    static float* weightPtrs[MAX_IN];
    ma_data_converter_config cfg;
    unsigned i;

    for (i = 0; i < chIn; ++i) {
        weightPtrs[i] = &weightsFlat[i*chOut];
    }

    cfg = ma_data_converter_config_init(inFmt, outFmt, chIn, chOut, 48000, 48000);
    cfg.channelMixMode = ma_channel_mix_mode_custom_weights;
    cfg.ppChannelWeights = weightPtrs;
    cfg.pChannelMapIn = g_mapIn3;
    cfg.pChannelMapOut = g_mapOut2;
    cfg.ditherMode = ma_dither_mode_none;
    if (ma_data_converter_init_preallocated(&cfg, g_heap, dc) != MA_SUCCESS) {
        fail("data converter init failed (%d -> %d)", (int)inFmt, (int)outFmt);
    }
}

static void check_data_converter_same_format(const fmt_def* f)
{
    /* Same rate and format. s16 is the s16-mid fixed-point path; u8/s24/s32 use an f32 mid format. */
    const mix_case* c = &g_cases[0];  /* cancellation */
    ma_int64 inSigned[MAX_IN];
    ma_int32 qw[MAX_IN];
    float weightsFlat[MAX_IN * MAX_OUT];
    ma_data_converter dc;
    ma_uint8 inBuf[GUARD_SIZE + MAX_FRAMES * MAX_IN * 4 + GUARD_SIZE];
    ma_uint8 outOne[GUARD_SIZE + MAX_FRAMES * MAX_OUT * 4 + GUARD_SIZE];
    ma_uint8 outChunk[GUARD_SIZE + MAX_FRAMES * MAX_OUT * 4 + GUARD_SIZE];
    ma_int64 expect;
    const size_t inFrameBytes  = (size_t)f->bytesPerSample * c->channelsIn;
    const size_t outFrameBytes = (size_t)f->bytesPerSample * MAX_OUT;
    ma_uint8* pIn = inBuf + GUARD_SIZE;
    ma_uint8* pOutOne = outOne + GUARD_SIZE;
    ma_uint8* pOutChunk = outChunk + GUARD_SIZE;
    unsigned i;
    int frame;

    build_case_frame(c, f, inSigned, qw, weightsFlat);
    if (f->id == ma_format_s16) {
        expect = ref_mix(inSigned, qw, c->channelsIn, f);       /* Fixed-point s16 mid format. */
    } else {
        expect = ref_f32_mid_mix(inSigned, c->channelsIn, weightsFlat, f->id, f->id);  /* f32 mid format. */
    }

    make_data_converter(f->id, f->id, c->channelsIn, MAX_OUT, weightsFlat, &dc);
    if (g_failures) return;

    fill_guards(inBuf, sizeof(inBuf));
    fill_guards(outOne, sizeof(outOne));
    for (frame = 0; frame < MAX_FRAMES; ++frame) {
        for (i = 0; i < c->channelsIn; ++i) {
            write_sample(f, pIn + frame*inFrameBytes + (size_t)i*f->bytesPerSample, inSigned[i]);
        }
    }

    {
        ma_uint64 framesIn = MAX_FRAMES;
        ma_uint64 framesOut = MAX_FRAMES;
        if (ma_data_converter_process_pcm_frames(&dc, pIn, &framesIn, pOutOne, &framesOut) != MA_SUCCESS) {
            fail("[dc %s/%s] process failed", f->name, f->name);
        }
        if (framesIn != MAX_FRAMES || framesOut != MAX_FRAMES) {
            fail("[dc %s/%s] frame counts %llu/%llu, want %d/%d", f->name, f->name,
                 (unsigned long long)framesIn, (unsigned long long)framesOut, MAX_FRAMES, MAX_FRAMES);
        }
    }
    check_guards("dc same-format output", outOne, sizeof(outOne));
    check_guards("dc same-format input", inBuf, sizeof(inBuf));

    for (frame = 0; frame < MAX_FRAMES; ++frame) {
        ma_int64 got = read_sample(f, pOutOne + frame*outFrameBytes);
        if (got != expect) {
            fail("[dc %s/%s] frame %d: got %lld want %lld", f->name, f->name, frame,
                 (long long)got, (long long)expect);
        }
    }

    /* Unequal chunks again, this time through the data converter API. */
    {
        static const ma_uint32 chunks[] = { 1, 2, 3 };
        ma_uint32 consumed = 0;
        ma_uint64 totalIn = 0;
        ma_uint64 totalOut = 0;
        size_t k;
        fill_guards(outChunk, sizeof(outChunk));
        for (k = 0; k < sizeof(chunks)/sizeof(chunks[0]); ++k) {
            ma_uint64 fin = chunks[k];
            ma_uint64 fout = chunks[k];
            ma_result r = ma_data_converter_process_pcm_frames(&dc,
                pIn + (size_t)consumed*inFrameBytes, &fin,
                pOutChunk + (size_t)consumed*outFrameBytes, &fout);
            if (r != MA_SUCCESS) {
                fail("[dc %s/%s] chunked process failed", f->name, f->name);
            }
            if (fin != chunks[k] || fout != chunks[k]) {
                fail("[dc %s/%s] chunk frame counts %llu/%llu, want %u/%u", f->name, f->name,
                     (unsigned long long)fin, (unsigned long long)fout, chunks[k], chunks[k]);
            }
            totalIn += fin;
            totalOut += fout;
            consumed += chunks[k];
        }
        if (totalIn != MAX_FRAMES || totalOut != MAX_FRAMES) {
            fail("[dc %s/%s] cumulative counts %llu/%llu, want %d/%d", f->name, f->name,
                 (unsigned long long)totalIn, (unsigned long long)totalOut, MAX_FRAMES, MAX_FRAMES);
        }
        check_guards("dc same-format chunked output", outChunk, sizeof(outChunk));
        if (memcmp(pOutOne, pOutChunk, (size_t)MAX_FRAMES*outFrameBytes) != 0) {
            fail("[dc %s/%s] chunked output differs from one-shot output", f->name, f->name);
        }
    }

    ma_data_converter_uninit(&dc, NULL);
    printf("[dc %s->%s] cancellation = %lld, chunking and frame counts OK\n",
           f->name, f->name, (long long)expect);
}

/*
Cross-format data converter pipelines. Every configuration below selects s16 as the mid format, so
the channel mix is checked against the wide-integer fixed-point reference applied to the s16 values
the pre-stage actually produces. Inputs are built so the pre-stage conversions land on exact
integers; post-stage expectations reproduce the library's integer-only conversion rules.
*/
typedef struct
{
    const char* name;
    ma_format inFmt;
    ma_format outFmt;
} cross_def;

static void check_data_converter_cross_format(void)
{
    static const ma_int16 s16Base[3] = { 30000, 30000, -30000 };
    static const cross_def crosses[] =
    {
        { "s32->s16", ma_format_s32, ma_format_s16 },  /* pre format conversion, mid s16 */
        { "s24->s16", ma_format_s24, ma_format_s16 },  /* pre format conversion, mid s16 */
        { "u8->s16",  ma_format_u8,  ma_format_s16 },  /* pre format conversion, mid s16 */
        { "s16->u8",  ma_format_s16, ma_format_u8  },  /* post format conversion, mid s16 */
        { "s16->s32", ma_format_s16, ma_format_s32 }   /* post format conversion, mid s16 */
    };
    static const fmt_def s16Def = { ma_format_s16, "s16", 2, -32768, 32767 };
    size_t k;

    for (k = 0; k < sizeof(crosses)/sizeof(crosses[0]); ++k) {
        const cross_def* x = &crosses[k];
        float weightsFlat[3*2] = { 1,0, 1,0, 1,0 };
        ma_data_converter dc;
        ma_uint8 inBuf[GUARD_SIZE + MAX_FRAMES * 3 * 4 + GUARD_SIZE];
        ma_uint8 outBuf[GUARD_SIZE + MAX_FRAMES * 2 * 4 + GUARD_SIZE];
        ma_uint8* pIn = inBuf + GUARD_SIZE;
        ma_uint8* pOut = outBuf + GUARD_SIZE;
        ma_int64 midSigned[3];   /* The s16 values the channel converter actually receives. */
        ma_int32 qw[3];
        ma_int64 midExpect;      /* The s16-domain mix result. */
        int frame;
        unsigned i;

        fill_guards(inBuf, sizeof(inBuf));
        fill_guards(outBuf, sizeof(outBuf));

        make_data_converter(x->inFmt, x->outFmt, 3, 2, weightsFlat, &dc);
        if (g_failures) return;

        for (i = 0; i < 3; ++i) {
            ma_int16 src = s16Base[i];
            midSigned[i] = src;
            if (x->inFmt == ma_format_s32) {
                /* s32 -> s16 is an arithmetic >>16, so feed src << 16 (unsigned shift to avoid signed-shift UB). */
                ma_int32 v = (ma_int32)((ma_uint32)src << 16);
                for (frame = 0; frame < MAX_FRAMES; ++frame) {
                    *(ma_int32*)(pIn + frame*3*4 + i*4) = v;
                }
            } else if (x->inFmt == ma_format_s24) {
                /* s24 -> s16 takes the top two bytes, so feed src << 8 (low byte zero). */
                ma_int32 v = (ma_int32)((ma_uint32)(ma_uint16)src << 8);
                for (frame = 0; frame < MAX_FRAMES; ++frame) {
                    ma_uint8* p = pIn + frame*3*3 + i*3;
                    p[0] = (ma_uint8)(v & 0xFF);
                    p[1] = (ma_uint8)((v >> 8) & 0xFF);
                    p[2] = (ma_uint8)((v >> 16) & 0xFF);
                }
            } else if (x->inFmt == ma_format_u8) {
                /* u8 -> s16 is (byte - 128) << 8; pick src so it stays exact: use src=29952 etc. */
                ma_int16 aligned = (ma_int16)((i == 2) ? -29952 : 29952);
                ma_uint8 byte = (ma_uint8)((aligned >> 8) + 128);
                midSigned[i] = aligned;
                for (frame = 0; frame < MAX_FRAMES; ++frame) {
                    pIn[frame*3 + i] = byte;
                }
            } else {
                for (frame = 0; frame < MAX_FRAMES; ++frame) {
                    *(ma_int16*)(pIn + frame*3*2 + i*2) = src;
                }
            }
        }

        for (i = 0; i < 3; ++i) {
            qw[i] = quantize_weight(weightsFlat[i*2]);
        }
        midExpect = ref_mix(midSigned, qw, 3, &s16Def);

        {
            ma_uint64 fin = MAX_FRAMES;
            ma_uint64 fout = MAX_FRAMES;
            if (ma_data_converter_process_pcm_frames(&dc, pIn, &fin, pOut, &fout) != MA_SUCCESS) {
                fail("[dc %s] process failed", x->name);
            }
            if (fin != MAX_FRAMES || fout != MAX_FRAMES) {
                fail("[dc %s] frame counts %llu/%llu", x->name,
                     (unsigned long long)fin, (unsigned long long)fout);
            }
        }
        check_guards(x->name, outBuf, sizeof(outBuf));
        check_guards(x->name, inBuf, sizeof(inBuf));

        for (frame = 0; frame < MAX_FRAMES; ++frame) {
            if (x->outFmt == ma_format_s16) {
                ma_int16 got = *(ma_int16*)(pOut + frame*2*2);
                if ((ma_int64)got != midExpect) {
                    fail("[dc %s] frame %d: got %d want %lld", x->name, frame, got, (long long)midExpect);
                }
            } else if (x->outFmt == ma_format_s32) {
                ma_int32 got = *(ma_int32*)(pOut + frame*2*4);
                ma_int64 want = midExpect << 16;   /* s16 -> s32 is <<16 */
                if ((ma_int64)got != want) {
                    fail("[dc %s] frame %d: got %d want %lld", x->name, frame, got, (long long)want);
                }
            } else {
                ma_uint8 got = pOut[frame*2];
                ma_uint8 want = (ma_uint8)((midExpect >> 8) + 128);  /* s16 -> u8 is (x>>8)+128 */
                if (got != want) {
                    fail("[dc %s] frame %d: got %u want %u", x->name, frame, (unsigned)got, (unsigned)want);
                }
                if (pOut[frame*2 + 1] != 128) {  /* Zero-weight second channel stays at the u8 silence byte on the s16-mid path. */
                    fail("[dc %s] frame %d ch1: got %u want 128", x->name, frame,
                         (unsigned)pOut[frame*2 + 1]);
                }
            }
        }

        ma_data_converter_uninit(&dc, NULL);
        printf("[dc %s] mid-s16 reference = %lld, output and frame counts OK\n",
               x->name, (long long)midExpect);
    }
}

/*
High-channel-count stress test. With 32 inputs at s32 full scale and unit weights the accumulator
holds 32 * 2^31 * 2^12 before the single divide - about 2.8e14, comfortably inside ma_int64. Two
patterns are checked: symmetric max/-max inputs that must cancel exactly, and all-max inputs whose
full sum overshoots and must be clipped only at the end. Run under UBSan by the shell script so any
signed overflow would fail the run.
*/
#define STRESS_CHANNELS 32

static void run_s32_stress(void)
{
    static const fmt_def s32Def = { ma_format_s32, "s32", 4, -2147483647LL - 1, 2147483647LL };
    float weightsFlat[STRESS_CHANNELS * MAX_OUT];
    float* weightPtrs[STRESS_CHANNELS];
    ma_int64 cancelSigned[STRESS_CHANNELS];
    ma_int64 clipSigned[STRESS_CHANNELS];
    ma_int32 qw[STRESS_CHANNELS];
    ma_int32 cancelIn[STRESS_CHANNELS];
    ma_int32 clipIn[STRESS_CHANNELS];
    ma_int32 cancelOut[MAX_OUT];
    ma_int32 clipOut[MAX_OUT];
    ma_int64 expectCancel;
    ma_int64 expectClip;
    ma_channel_converter_config cfg;
    ma_channel_converter conv;
    unsigned i;

    for (i = 0; i < STRESS_CHANNELS; ++i) {
        weightsFlat[i*2 + 0] = 1.0f;
        weightsFlat[i*2 + 1] = 0.0f;
        weightPtrs[i] = &weightsFlat[i*2];
        qw[i] = quantize_weight(1.0f);
        cancelSigned[i] = (i < STRESS_CHANNELS/2) ? s32Def.maxValue : -s32Def.maxValue;
        clipSigned[i] = s32Def.maxValue;
        cancelIn[i] = (ma_int32)cancelSigned[i];
        clipIn[i] = (ma_int32)clipSigned[i];
    }

    expectCancel = ref_mix(cancelSigned, qw, STRESS_CHANNELS, &s32Def);
    expectClip   = ref_mix(clipSigned,   qw, STRESS_CHANNELS, &s32Def);

    cfg = ma_channel_converter_config_init(ma_format_s32, STRESS_CHANNELS, NULL, MAX_OUT, NULL, ma_channel_mix_mode_custom_weights);
    cfg.ppWeights = weightPtrs;
    if (ma_channel_converter_init_preallocated(&cfg, g_heap, &conv) != MA_SUCCESS) {
        fail("[s32 stress] init failed");
        return;
    }

    if (ma_channel_converter_process_pcm_frames(&conv, cancelOut, cancelIn, 1) != MA_SUCCESS ||
        ma_channel_converter_process_pcm_frames(&conv, clipOut,   clipIn,   1) != MA_SUCCESS) {
        fail("[s32 stress] process failed");
    }

    if ((ma_int64)cancelOut[0] != expectCancel || cancelOut[1] != 0) {
        fail("[s32 stress] cancellation: got %d/%d want %lld/0", cancelOut[0], cancelOut[1],
             (long long)expectCancel);
    }
    if ((ma_int64)clipOut[0] != expectClip || clipOut[1] != 0) {
        fail("[s32 stress] clipping: got %d/%d want %lld/0", clipOut[0], clipOut[1],
             (long long)expectClip);
    }

    printf("[s32 stress] %d-channel cancellation = %lld, full-scale sum clipped to %lld\n",
           STRESS_CHANNELS, (long long)expectCancel, (long long)expectClip);
    ma_channel_converter_uninit(&conv, NULL);
}

int main(void)
{
    int fi;
    int ci;

    printf("== ma_channel_converter integer weighted mixing ==\n");
    for (fi = 0; fi < FORMAT_COUNT; ++fi) {
        const fmt_def* f = &g_formats[fi];
        for (ci = 0; ci < CASE_COUNT; ++ci) {
            run_channel_converter_case(&g_cases[ci], f);
        }
    }
    run_f32_case();
    run_s32_stress();

    printf("== permutation invariance checked inside every format/case above ==\n");

    printf("== ma_data_converter, same rate and format ==\n");
    for (fi = 0; fi < FORMAT_COUNT; ++fi) {
        check_data_converter_same_format(&g_formats[fi]);
    }

    printf("== ma_data_converter with pre/post format conversion (mid format references) ==\n");
    check_data_converter_cross_format();

    if (g_failures == 0) {
        printf("ALL CHECKS PASSED\n");
        return 0;
    }

    printf("%d CHECK(S) FAILED\n", g_failures);
    return 1;
}
