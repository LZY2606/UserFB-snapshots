import assert from 'node:assert/strict';
import { AnimationClip } from '../src/animation/AnimationClip.js';
import { NumberKeyframeTrack } from '../src/animation/tracks/NumberKeyframeTrack.js';
import { AnimationMixer } from '../src/animation/AnimationMixer.js';
import { Object3D } from '../src/core/Object3D.js';
import { subclip } from '../src/animation/AnimationUtils.js';
import { InterpolateSmooth } from '../src/constants.js';
const track=new NumberKeyframeTrack('.position[x]',[0,1,2,3],[0,2,-1,4],InterpolateSmooth);
const clip=new AnimationClip('source',3,[track]);
const sample=track.createInterpolant().evaluate(0.5)[0];
assert.ok(Math.abs(sample-1.3125)<1e-6);
const cut=subclip(clip,'cut',0.5,2.5,1);
assert.equal(cut.duration,1);
assert.deepEqual(Array.from(cut.tracks[0].times),[0,1]);
const obj=new Object3D(), mixer=new AnimationMixer(obj);
mixer.clipAction(clip).play();mixer.update(0.5);
assert.ok(Number.isFinite(obj.position.x));
console.log('THREE_CURRENT_SAMPLE_OK value='+sample);
console.log('THREE_LEGACY_CUT_OK duration='+cut.duration);
