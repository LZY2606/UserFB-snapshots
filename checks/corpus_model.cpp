static std::string FixturePath() {
  const char *Candidates[] = {
      ".task-build/merge-fixture",
      "./.task-build/merge-fixture",
  };
  for (const char *P : Candidates)
    if (IsFile(P))
      return P;
  // Fall back relative to this source file (checks/corpus_model.cpp).
  return std::string(__FILE__).substr(0,
                                      std::strlen(__FILE__) -
                                          std::strlen("corpus_model.cpp")) +
         "../.task-build/merge-fixture";
}

static void WriteInput(const std::string &Path, const std::string &Bytes) {
  WriteToFile(reinterpret_cast<const uint8_t *>(Bytes.data()), Bytes.size(),
              Path);
}

static std::string ShaBasename(const Unit &U) { return Hash(U); }

// Generates one finite, fixed-seed trajectory of byte strings, capped in
// length and step count; only characters the benign fixture branches on.
static std::vector<std::string> GenTrajectory(uint32_t Seed, size_t MaxSteps) {
  TinyLCG Rng(Seed);
  const char Alphabet[] = {'A', 'B', 'C', 'Z'};
  std::vector<std::string> Out;
  std::set<std::string> Seen;
  for (size_t Step = 0; Step < MaxSteps; ++Step) {
    size_t Len = 1 + Rng.Below(6);
    std::string S;
    for (size_t I = 0; I < Len; ++I)
      S.push_back(Alphabet[Rng.Below(4)]);
    if (!Seen.insert(S).second)
      continue;
    Out.push_back(S);
  }
  return Out;
}

static int RunFixtureE2E(uint32_t Seed) {
  std::ostringstream Ctx;
  Ctx << "e2e seed=" << Seed;
  G_ctx = Ctx.str();
  const char *Tmp = getenv("TMPDIR");
  std::string Base = Tmp ? Tmp : ".";
  std::string Tmpl = Base + "/corp-model-XXXXXX";
  std::vector<char> TmplBuf(Tmpl.begin(), Tmpl.end());
  TmplBuf.push_back(0);
  char *Dir = mkdtemp(TmplBuf.data());
  CK(Dir != nullptr);
  std::string Root = Dir;
  std::string OldDir = Root + "/old";
  std::string NewDir = Root + "/new";
  MkDir(OldDir);
  MkDir(NewDir);
  std::string Control = Root + "/control.txt";

  std::vector<std::string> Traj = GenTrajectory(Seed, /*MaxSteps=*/7);
  CK(Traj.size() >= 3);
  size_t Split = 1 + (Traj.size() % (Traj.size() - 1)); // 1..size-1 old files
  CK(Split >= 1 && Split < Traj.size());
  struct Placed {
    std::string Path;
    std::string Bytes;
  };
  std::vector<Placed> OldInputs, NewInputs;
  for (size_t I = 0; I < Traj.size(); ++I) {
    bool IsOld = I < Split;
    std::string DirP = IsOld ? OldDir : NewDir;
    std::string Path = DirP + "/in" + std::to_string(I);
    WriteInput(Path, Traj[I]);
    (IsOld ? OldInputs : NewInputs).push_back({Path, Traj[I]});
  }
  // Snapshot the old directory so the original input set can be restored.
  Vector<SizedFile> OldBefore;
  GetSizedFilesFromDir(OldDir, &OldBefore);
  std::set<std::string> OldBeforeNames;
  for (const auto &SF : OldBefore)
    OldBeforeNames.insert(SF.File);

  std::string Fixture = FixturePath();
  CK(IsFile(Fixture));
  std::string Cmd = Fixture + " -merge=1 -merge_control_file=" + Control +
                    " " + OldDir + " " + NewDir + " >" + Root + "/out1.txt 2>&1";
  int RC = system(Cmd.c_str());
  CK(WIFEXITED(RC) && WEXITSTATUS(RC) == 0);
  CK(FileSize(Control) > 0);

  // Real log: production parse and independent model parse must agree.
  std::string Log1 = FileToString(Control);
  Merger M;
  CK(M.Parse(Log1, true));
  ModelJournal MJ = ParseModelJournal(Log1, true);
  CK(MJ.Ok);
  CK(M.Files.size() == MJ.Files.size());
  CK(M.Files.size() == Traj.size());
  CK(M.NumFilesInFirstCorpus == OldInputs.size());
  CK(M.FirstNotProcessedFile == Traj.size());
  CK(M.LastFailure.empty());
  for (size_t I = 0; I < MJ.Files.size(); ++I) {
    std::ostringstream RecCtx;
    RecCtx << G_ctx << " step=" << I
           << " record=" << MJ.Files[I].Name << " size=" << MJ.Files[I].Size
           << " feat=" << SetToStr(MJ.Files[I].Features)
           << " pc=" << SetToStr(MJ.Files[I].PCs);
    G_ctx = RecCtx.str();
    CK(M.Files[I].Name == MJ.Files[I].Name);
    CK(SameSet(M.Files[I].Features, MJ.Files[I].Features));
    CK(SameSet(M.Files[I].Cov, MJ.Files[I].PCs));
    // Record size must equal the actual on-disk byte count.
    Unit Actual = FileToVector(MJ.Files[I].Name);
    CK(Actual.size() == MJ.Files[I].Size);
    CK(M.Files[I].Size == Actual.size());
  }
  G_ctx = "e2e seed=" + std::to_string(Seed) + " merge";

  // Offline model on the real bytes/log: fresh parse, empty containers.
  std::set<uint32_t> EmptyFeat, EmptyPC;
  Merger M2;
  std::set<uint32_t> NewFeat, NewPCs;
  std::set<std::string> Selected;
  CK(RunProductionMerge(Log1, EmptyFeat, EmptyPC, &M2, &NewFeat, &NewPCs,
                        &Selected) == 0);
  MergePrediction MP = PredictMerge(MJ, EmptyFeat, EmptyPC);
  CK(NewFeat == MP.NewFeatures);
  CK(NewPCs == MP.NewPCs);
  CK(CheckSelection(M2, EmptyFeat, Selected, MP) == 0);

  // Selected files land in the output (old) directory named by SHA, with
  // contents identical to the input bytes.
  Vector<SizedFile> OldAfter;
  GetSizedFilesFromDir(OldDir, &OldAfter);
  std::set<std::string> OldAfterNames;
  for (const auto &SF : OldAfter)
    OldAfterNames.insert(SF.File);
  std::set<std::string> AllInputBytes;
  for (const auto &P : OldInputs)
    AllInputBytes.insert(P.Bytes);
  for (const auto &P : NewInputs)
    AllInputBytes.insert(P.Bytes);
  for (const std::string &Name : Selected) {
    Unit U = FileToVector(Name);
    std::string HashName = ShaBasename(U);
    std::string OutPath = OldDir + "/" + HashName;
    CK(IsFile(OutPath));
    CK(OldAfterNames.count(OutPath)); // named by SHA inside the output corpus
    Unit Out = FileToVector(OutPath);
    CK(Out == U);
    CK(AllInputBytes.count(std::string(U.begin(), U.end())));
  }

  // Online replay of the real records follows RunOne ordering and is checked
  // against the same independent ownership model used by the synthetic cases.
  // InputCorpus holds multi-megabyte feature arrays, so keep it on the heap.
  // The real FT log only carries features no earlier record has seen, so no
  // feature id is repeated here; shared-feature takeovers therefore come from
  // the synthetic ownership cases, not from this log.
  std::set<uint32_t> AllLoggedFeatures, TailPCs;
  for (const auto &F : MJ.Files)
    AllLoggedFeatures.insert(F.Features.begin(), F.Features.end());
  // Merge only collects NewCov from the new-corpus (tail) files, so the
  // expected PC set excludes PCs seen solely in the initial corpus.
  for (size_t I = MJ.NumFirst; I < MJ.Files.size(); ++I)
    TailPCs.insert(MJ.Files[I].PCs.begin(), MJ.Files[I].PCs.end());
  {
    std::unique_ptr<InputCorpus> C(new InputCorpus(""));
    OnlineModel OM;
    for (size_t I = 0; I < MJ.Files.size(); ++I) {
      std::ostringstream RecCtx;
      RecCtx << "e2e seed=" << Seed << " online step=" << I
             << " record=" << MJ.Files[I].Name;
      G_ctx = RecCtx.str();
      Unit U = FileToVector(MJ.Files[I].Name);
      std::vector<uint32_t> Ids(MJ.Files[I].Features.begin(),
                                MJ.Files[I].Features.end());
      CK(OM.Step(*C, OnlineStep{U, Ids}, true) == 0);
    }
    CK(C->NumFeatures() == AllLoggedFeatures.size());
    // Every logged feature has exactly one surviving owner.
    CK(OM.SlotOwner.size() == AllLoggedFeatures.size());
    CK(NewPCs == TailPCs); // no initial PCs: tail PCs are exactly the new ones
  }

  // Restore the original old-directory input set, then re-run: with the log
  // already complete for exactly this file set, the outer merge returns
  // immediately and appends no records.  No file copying is required here.
  Vector<SizedFile> OldNow;
  GetSizedFilesFromDir(OldDir, &OldNow);
  for (const auto &SF : OldNow)
    if (!OldBeforeNames.count(SF.File))
      RemoveFile(SF.File);
  Vector<SizedFile> OldRestored;
  GetSizedFilesFromDir(OldDir, &OldRestored);
  CK(OldRestored.size() == OldBefore.size());
  std::string LogBefore = FileToString(Control);
  std::string Cmd2 = Fixture + " -merge=1 -merge_control_file=" + Control +
                     " " + OldDir + " " + NewDir + " >" + Root +
                     "/out2.txt 2>&1";
  RC = system(Cmd2.c_str());
  CK(WIFEXITED(RC) && WEXITSTATUS(RC) == 0);
  std::string LogAfter = FileToString(Control);
  CK(LogAfter == LogBefore); // no appended records, fast completion path

  RmDirRecursive(Root);
  G_ctx.clear();
  return 0;
}

