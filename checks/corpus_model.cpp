//===- corpus_model.cpp ---------------------------------------------------===//
//
// Deterministic, replayable model tests for the production Merger and
// InputCorpus.  The production classes are exercised directly through their
// real interfaces; nothing below re-implements them.  The "model" is an
// independent, small-scale derivation of the same records and invariants:
//
//   * a hand-written parser for STARTED/FT/COV control logs that re-derives
//     file records, resume progress, feature sets and first PC ownership;
//   * an independent greedy merge prediction (subtract known features, sort
//     by size then residual feature count, greedily select);
//   * an independent feature-to-smallest-input ownership map that follows
//     Fuzzer::RunOne's real call order (AddFeature first, AddToCorpus after).
//
// All inputs are finite, locally generated byte strings; feature and PC
// numbers are chosen in range.  No target process is ever crashed.
//
//===----------------------------------------------------------------------===//

