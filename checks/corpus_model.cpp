int CaseOwnershipReplaceAndSampling() {
  G_ctx = "ownership_replace_sampling";
  std::unique_ptr<InputCorpus> CP(new InputCorpus(""));
  InputCorpus &C = *CP;
  OnlineModel OM;
  CK(OM.Step(C, OnlineStep{MakeUnit("ABCDE"), {50, 51}}, true) == 0);
  CK(OM.Step(C, OnlineStep{MakeUnit("FGH"), {52}}, true) == 0);
  // Strictly smaller so the takeover happens: idx 2 takes feature 51, idx 0
  // keeps feature 50.  All three inputs stay active with distinct sizes.
  CK(OM.Step(C, OnlineStep{MakeUnit("IJ"), {51}}, true) == 0);
  // Replace on every still-active input: identity, Reduced, contents, count.
  std::vector<size_t> Active(OM.Active.begin(), OM.Active.end());
  CK(Active.size() == 3);
  for (size_t K = 0; K < Active.size(); ++K) {
    size_t Idx = Active[K];
    InputInfo *II = OM.IIs[Idx];
    std::string OldHash = Sha1ToString(II->Sha1);
    Unit Smaller = Unit(II->U.begin(), II->U.begin() + II->U.size() - 1);
    CK(II->U.size() > Smaller.size());
    C.Replace(II, Smaller);
    std::string NewHash = Sha1ToString(II->Sha1);
    CK(OldHash != NewHash);
    CK(II->Reduced);
    CK(II->U == Smaller);
    CK(!C.HasUnit(OldHash));
    CK(C.HasUnit(NewHash));
    OM.TotalBytes -= 1;
  }
  CK(OM.Check(C) == 0); // active count and feature ownership survive Replace
  // A later, smaller candidate evicts one active input outright: the emptied
  // slot must never be returned by the sampler below.
  CK(OM.Step(C, OnlineStep{MakeUnit("W"), {52}}, true) == 0);
  CK(OM.IIs[1]->U.empty());
  CK(OM.Check(C) == 0);
  // Fixed-seed sampling with a hard step cap: ownership checks only, never a
  // fixed library sequence or a probability-ratio threshold.
  Random Rand(0xC0FFEEu);
  const size_t kSteps = 40000;
  std::set<size_t> Picked;
  for (size_t Step = 0; Step < kSteps; ++Step) {
    size_t Choice = C.ChooseUnitIdxToMutate(Rand);
    CK(Choice < C.size());
    InputInfo *II = OM.IIs[Choice];
    CK(!II->U.empty());          // only non-empty inputs may be returned
    CK(II->NumFeatures > 0);     // only inputs still owning a feature
    Picked.insert(Choice);
  }
  CK(Picked == OM.Active); // every active input reachable, no inactive one
  CK(!Picked.count(1));    // the evicted input is never sampled
  return 0;
}

