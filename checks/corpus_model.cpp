// Failure context: seed / step / minimal record are carried here so that any
// assertion can report the trajectory position that produced them.
std::string G_ctx;

#define CK(x)                                                                 \
  do {                                                                         \
    if (!task_check(!!(x), #x, __FILE__, __LINE__)) {                         \
      fprintf(stderr, "        context: %s\n", G_ctx.c_str());                \
      return 1;                                                                \
    }                                                                          \
  } while (0)

static std::string SetToStr(const std::set<uint32_t> &S) {
  std::ostringstream OS;
  OS << "{";
  for (auto V : S)
    OS << V << ",";
  OS << "}";
  return OS.str();
}

static std::set<uint32_t> ToSet(const Vector<uint32_t> &V) {
  return std::set<uint32_t>(V.begin(), V.end());
}

static bool SameSet(const Vector<uint32_t> &V,
                    const std::set<uint32_t> &S) {
  return ToSet(V) == S;
}

//===----------------------------------------------------------------------===//
// Synthetic control-log generation and the independent log model.
//===----------------------------------------------------------------------===//

struct FileSpec {
  std::string Name;
  size_t Size;
  std::vector<uint32_t> Features; // full, in-range feature numbers
  std::vector<uint32_t> PCs;      // full, in-range PC table indices
};

struct JournalSpec {
  size_t NumFirst = 0;
  std::vector<FileSpec> Files;
  // When true the last file only gets a STARTED line, modelling a task that
  // was stopped cleanly and left resume metadata behind.
  bool TrailingStartedOnly = false;
};

// Builds a control log.  With coverage enabled every completed record is
// STARTED/FT/COV; with coverage disabled the FT/COV markers are still present
// (the inner process always writes them) but carry no numbers.
static std::string BuildJournal(const JournalSpec &Spec, bool CovEnabled) {
  std::ostringstream OS;
  OS << Spec.Files.size() << "\n";
  OS << Spec.NumFirst << "\n";
  for (const auto &F : Spec.Files)
    OS << F.Name << "\n";
  for (size_t I = 0; I < Spec.Files.size(); ++I) {
    const auto &F = Spec.Files[I];
    OS << "STARTED " << I << " " << F.Size << "\n";
    bool Last = I + 1 == Spec.Files.size();
    if (Spec.TrailingStartedOnly && Last)
      break;
    OS << "FT " << I;
    if (CovEnabled)
      for (uint32_t Feat : F.Features)
        OS << " " << Feat;
    OS << "\n";
    OS << "COV " << I;
    if (CovEnabled)
      for (uint32_t PC : F.PCs)
        OS << " " << PC;
    OS << "\n";
  }
  return OS.str();
}

struct ModelFile {
  std::string Name;
  size_t Size = 0;
  bool Started = false;
  bool Completed = false;
  std::set<uint32_t> Features;
  std::set<uint32_t> PCs;
};

struct ModelJournal {
  bool Ok = false;
  size_t NumFiles = 0;
  size_t NumFirst = 0;
  std::vector<ModelFile> Files;
  size_t FirstNotProcessed = 0;
  std::string LastFailure;
};

// Independent line-at-a-time re-derivation of a control log.
static ModelJournal ParseModelJournal(const std::string &Log,
                                      bool CovEnabled) {
  ModelJournal MJ;
  std::istringstream IS(Log);
  std::string Line;
  if (!std::getline(IS, Line, '\n'))
    return MJ;
  {
    std::istringstream L(Line);
    L >> MJ.NumFiles;
    if (!MJ.NumFiles || MJ.NumFiles > 10000000)
      return MJ;
  }
  if (!std::getline(IS, Line, '\n'))
    return MJ;
  {
    std::istringstream L(Line);
    L >> MJ.NumFirst;
    if (MJ.NumFirst > MJ.NumFiles)
      return MJ;
  }
  MJ.Files.resize(MJ.NumFiles);
  for (size_t I = 0; I < MJ.NumFiles; ++I) {
    if (!std::getline(IS, MJ.Files[I].Name, '\n'))
      return MJ;
  }
  size_t Expected = 0;
  ssize_t LastStarted = -1;
  std::set<uint32_t> GloballySeenPCs; // COV dedups across the whole log
  while (std::getline(IS, Line, '\n')) {
    std::istringstream L(Line);
    std::string Marker;
    size_t Idx = 0;
    L >> Marker >> Idx;
    if (Marker == "STARTED") {
      if (Idx != Expected)
        return MJ;
      size_t RecSize = 0;
      L >> RecSize;
      MJ.Files[Idx].Size = RecSize;
      MJ.Files[Idx].Started = true;
      LastStarted = static_cast<ssize_t>(Idx);
      ++Expected;
    } else if (Marker == "FT") {
      if (LastStarted < 0 ||
          static_cast<size_t>(LastStarted) != Idx)
        return MJ;
      LastStarted = -1;
      if (CovEnabled) {
        uint32_t Feat = 0;
        while (L >> Feat)
          MJ.Files[Idx].Features.insert(Feat);
        MJ.Files[Idx].Completed = true;
      }
    } else if (Marker == "COV") {
      if (!CovEnabled)
        continue;
      uint32_t PC = 0;
      while (L >> PC)
        if (GloballySeenPCs.insert(PC).second)
          MJ.Files[Idx].PCs.insert(PC);
    } else {
      return MJ;
    }
  }
  if (LastStarted >= 0)
    MJ.LastFailure = MJ.Files[LastStarted].Name;
  MJ.FirstNotProcessed = Expected;
  MJ.Ok = true;
  return MJ;
}

// Cross-checks a production Merger against the independent model parsed from
// the same log text.
static int CheckMergerAgainstModel(const std::string &Log, bool CovEnabled,
                                   size_t ExpectFirstNotProcessed,
                                   const std::string &ExpectLastFailure) {
  Merger M; // fresh Merger for every parse, as required.
  CK(M.Parse(Log, CovEnabled));
  ModelJournal MJ = ParseModelJournal(Log, CovEnabled);
  CK(MJ.Ok);
  CK(M.Files.size() == MJ.Files.size());
  CK(M.NumFilesInFirstCorpus == MJ.NumFirst);
  CK(M.FirstNotProcessedFile == MJ.FirstNotProcessed);
  CK(M.FirstNotProcessedFile == ExpectFirstNotProcessed);
  CK(M.LastFailure == MJ.LastFailure);
  CK(M.LastFailure == ExpectLastFailure);
  for (size_t I = 0; I < MJ.Files.size(); ++I) {
    const auto &MF = MJ.Files[I];
    const auto &PF = M.Files[I];
    CK(PF.Name == MF.Name);
    CK(PF.Size == MF.Size);
    CK(SameSet(PF.Features, MF.Features));
    CK(SameSet(PF.Cov, MF.PCs));
    if (!CovEnabled) {
      // Coverage switched off: nothing must be collected.
      CK(PF.Features.empty());
      CK(PF.Cov.empty());
    }
  }
  return 0;
}

// Cuts a log after exactly N complete record groups (a record group is the
// STARTED line plus its FT/COV lines); truncation only ever happens on a
// completed-record boundary, never in the middle of a group.
static std::string CutAfterRecords(const std::string &Log, size_t Records) {
  if (Records == 0)
    return "";
  size_t Pos = 0;
  size_t StartedSeen = 0;
  size_t CutPos = std::string::npos;
  while (Pos < Log.size()) {
    size_t End = Log.find('\n', Pos);
    if (End == std::string::npos)
      break;
    std::string Line = Log.substr(Pos, End - Pos);
    size_t Next = End + 1;
    if (Line.compare(0, 7, "STARTED") == 0) {
      ++StartedSeen;
      if (StartedSeen == Records + 1) {
        // The next group begins here: keep everything before this line.
        CutPos = Pos;
        break;
      }
    }
    Pos = Next;
  }
  if (CutPos == std::string::npos)
    CutPos = Log.size(); // the last group runs to the end of the log
  return Log.substr(0, CutPos);
}

//===----------------------------------------------------------------------===//
// Independent merge prediction.
//===----------------------------------------------------------------------===//

struct MergePrediction {
  std::set<uint32_t> NewFeatures;
  std::set<uint32_t> NewPCs;
  std::set<std::string> SelectedNames;
  bool HasOrderTie = false; // same (size, residual feature count) among cands
};

// Mirrors the production greedy algorithm on the model's own structures:
// subtract every already-known feature, rank by (size asc, residual count
// desc), then make one greedy pass.  PC accounting is independent of file
// selection.
static MergePrediction PredictMerge(const ModelJournal &MJ,
                                    const std::set<uint32_t> &InitialFeatures,
                                    const std::set<uint32_t> &InitialPCs) {
  MergePrediction MP;
  std::set<uint32_t> Known = InitialFeatures;
  for (size_t I = 0; I < MJ.NumFirst && I < MJ.Files.size(); ++I) {
    const auto &Feat = MJ.Files[I].Features;
    Known.insert(Feat.begin(), Feat.end());
  }
  struct Cand {
    std::string Name;
    size_t Size;
    std::set<uint32_t> Residual;
    std::set<uint32_t> PCs;
  };
  std::vector<Cand> Cands;
  for (size_t I = MJ.NumFirst; I < MJ.Files.size(); ++I) {
    Cand C;
    C.Name = MJ.Files[I].Name;
    C.Size = MJ.Files[I].Size;
    C.PCs = MJ.Files[I].PCs;
    for (uint32_t Feat : MJ.Files[I].Features)
      if (!Known.count(Feat))
        C.Residual.insert(Feat);
    Cands.push_back(C);
  }
  for (size_t I = 0; I < Cands.size(); ++I)
    for (size_t J = I + 1; J < Cands.size(); ++J)
      if (Cands[I].Size == Cands[J].Size &&
          Cands[I].Residual.size() == Cands[J].Residual.size())
        MP.HasOrderTie = true;
  std::sort(Cands.begin(), Cands.end(),
            [](const Cand &A, const Cand &B) {
              if (A.Size != B.Size)
                return A.Size < B.Size;
              return A.Residual.size() > B.Residual.size();
            });
  std::set<uint32_t> All = Known;
  for (const auto &C : Cands) {
    bool Added = false;
    for (uint32_t Feat : C.Residual)
      if (All.insert(Feat).second) {
        Added = true;
        MP.NewFeatures.insert(Feat);
      }
    if (Added)
      MP.SelectedNames.insert(C.Name);
    // PCs accumulate regardless of whether the file gets selected.
    for (uint32_t PC : C.PCs)
      if (!InitialPCs.count(PC))
        MP.NewPCs.insert(PC);
  }
  return MP;
}

static int RunProductionMerge(const std::string &Log,
                              const std::set<uint32_t> &InitialFeatures,
                              const std::set<uint32_t> &InitialPCs,
                              Merger *OutM,
                              std::set<uint32_t> *OutNewFeatures,
                              std::set<uint32_t> *OutNewPCs,
                              std::set<std::string> *OutSelected) {
  Merger M; // re-parsed object per merge; output containers start empty.
  CK(M.Parse(Log, true));
  Set<uint32_t> IF(InitialFeatures.begin(), InitialFeatures.end());
  Set<uint32_t> IC(InitialPCs.begin(), InitialPCs.end());
  Set<uint32_t> NewFeatures, NewCov;
  Vector<std::string> NewFiles;
  size_t Ret = M.Merge(IF, &NewFeatures, IC, &NewCov, &NewFiles);
  CK(Ret == NewFeatures.size());
  *OutNewFeatures = std::set<uint32_t>(NewFeatures.begin(), NewFeatures.end());
  *OutNewPCs = std::set<uint32_t>(NewCov.begin(), NewCov.end());
  OutSelected->clear();
  for (const auto &N : NewFiles)
    OutSelected->insert(N);
  *OutM = M;
  return 0;
}

// Replays the greedy pass on the production Merger's own post-Merge ordering
// using independent bookkeeping, proving every selected file genuinely added
// a new feature in that order and that the (size, residual count) ordering
// invariant holds between adjacent tail entries.
static int ReplayGreedyOnProductionOrder(
    const Merger &M, const std::set<uint32_t> &Initial,
    const std::set<std::string> &ProductionSelected) {
  std::set<uint32_t> Known = Initial;
  for (size_t I = 0; I < M.NumFilesInFirstCorpus; ++I)
    for (uint32_t Feat : M.Files[I].Features)
      Known.insert(Feat);
  std::set<std::string> IndependentlySelected;
  for (size_t I = M.NumFilesInFirstCorpus; I < M.Files.size(); ++I) {
    bool AnyNew = false;
    for (uint32_t Feat : M.Files[I].Features)
      if (Known.insert(Feat).second)
        AnyNew = true;
    if (AnyNew)
      IndependentlySelected.insert(M.Files[I].Name);
    if (I > M.NumFilesInFirstCorpus) {
      const auto &Prev = M.Files[I - 1];
      const auto &Cur = M.Files[I];
      CK(Prev.Size <= Cur.Size);
      if (Prev.Size == Cur.Size)
        CK(Prev.Features.size() >= Cur.Features.size());
    }
  }
  CK(IndependentlySelected == ProductionSelected);
  return 0;
}

// Set-level selection check that honours the documented tie rule.
static int CheckSelection(const Merger &M,
                          const std::set<uint32_t> &InitialFeatures,
                          const std::set<std::string> &ProductionSelected,
                          const MergePrediction &MP) {
  if (!MP.HasOrderTie) {
    CK(ProductionSelected == MP.SelectedNames);
    return 0;
  }
  // With a legal tie any ordering is acceptable; the greedy replay on the
  // production order is the authoritative validity check here.
  return ReplayGreedyOnProductionOrder(M, InitialFeatures,
                                       ProductionSelected);
}

//===----------------------------------------------------------------------===//
// Online corpus: independent smallest-input-per-feature ownership model.
//===----------------------------------------------------------------------===//

static const size_t kModelFeatureSetSize = 1u << 21; // keep in sync with corpus

struct OnlineStep {
  Unit Bytes;
  std::vector<uint32_t> FeatureIds;
};

struct OnlineModel {
  struct Owner {
    size_t InputIdx;
    uint32_t Size;
  };
  std::map<size_t, Owner> SlotOwner;   // feature slot -> current owner
  std::map<size_t, size_t> OwnedCount; // corpus index -> slots owned
  std::set<size_t> Active;             // corpus indices whose Unit is non-empty
  std::vector<InputInfo *> IIs;
  size_t DistinctSlots = 0;
  size_t Updates = 0;
  size_t TotalBytes = 0;

  // Feeds one candidate through the real corpus in Fuzzer::RunOne order:
  // every AddFeature first, then a single AddToCorpus iff something moved.
  int Step(InputCorpus &C, const OnlineStep &S, bool Shrink) {
    CK(!S.Bytes.empty());
    const size_t Idx = IIs.size();
    // First pass: derive the expected ownership transition on the model maps.
    std::vector<uint32_t> Acquired;
    std::vector<size_t> Evicted;
    for (uint32_t Id : S.FeatureIds) {
      size_t Slot = static_cast<size_t>(Id) % kModelFeatureSetSize;
      auto It = SlotOwner.find(Slot);
      bool Take = It == SlotOwner.end() ||
                  (Shrink && It->second.Size > S.Bytes.size());
      if (!Take)
        continue;
      Acquired.push_back(Id);
      ++Updates;
      if (It == SlotOwner.end()) {
        ++DistinctSlots;
      } else {
        size_t OldIdx = It->second.InputIdx;
        CK(OwnedCount[OldIdx] > 0);
        if (--OwnedCount[OldIdx] == 0) {
          // Loses its last feature in this step; production will empty it.
          TotalBytes -= IIs[OldIdx]->U.size();
          CK(Active.erase(OldIdx) == 1);
          Evicted.push_back(OldIdx);
        }
      }
      SlotOwner[Slot] = Owner{Idx, static_cast<uint32_t>(S.Bytes.size())};
    }
    // Drive the real corpus with the same call sequence.
    std::vector<uint32_t> RealAcquired;
    for (uint32_t Id : S.FeatureIds) {
      if (C.AddFeature(Id, static_cast<uint32_t>(S.Bytes.size()), Shrink))
        RealAcquired.push_back(Id);
    }
    CK(RealAcquired == Acquired);
    CK(C.NumFeatures() == DistinctSlots);
    CK(C.NumFeatureUpdates() == Updates);
    if (Acquired.empty())
      return Check(C); // RunOne does not call AddToCorpus without new features
    // The real corpus must have emptied every input the model just evicted.
    for (size_t OldIdx : Evicted)
      CK(IIs[OldIdx]->U.empty());
    DataFlowTrace DFT;
    Vector<uint32_t> FS(Acquired.begin(), Acquired.end());
    InputInfo *II = C.AddToCorpus(S.Bytes, Acquired.size(), false, false, FS,
                                  DFT, nullptr);
    IIs.push_back(II);
    OwnedCount[Idx] = Acquired.size();
    Active.insert(Idx);
    TotalBytes += S.Bytes.size();
    return Check(C);
  }

  int Check(InputCorpus &C) const {
    CK(C.NumFeatures() == DistinctSlots);
    CK(C.NumFeatureUpdates() == Updates);
    CK(C.NumActiveUnits() == Active.size());
    CK(C.SizeInBytes() == TotalBytes);
    CK(C.size() == IIs.size());
    for (size_t I = 0; I < IIs.size(); ++I) {
      const InputInfo *II = IIs[I];
      size_t ExpectOwned = OwnedCount.count(I) ? OwnedCount.find(I)->second : 0;
      CK(II->NumFeatures == ExpectOwned);
      if (Active.count(I)) {
        CK(!II->U.empty());
      } else {
        CK(II->U.empty());
        CK(ExpectOwned == 0);
      }
    }
    return 0;
  }
};

static Unit MakeUnit(const std::string &S) {
  return Unit(S.begin(), S.end());
}

