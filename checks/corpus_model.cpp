// Small deterministic LCG used to sweep combinations: candidate lengths, old
// corpus counts, InitialFeatures and InitialPCs all participate.
struct TinyLCG {
  uint32_t State;
  explicit TinyLCG(uint32_t Seed) : State(Seed ? Seed : 1) {}
  uint32_t Next() {
    State = State * 1664525u + 1013904223u;
    return State;
  }
  uint32_t Below(uint32_t N) { return N ? Next() % N : 0; }
};

int CaseProjectionComboSweep() {
  G_ctx = "projection_combo_sweep";
  TinyLCG Rng(20261127u);
  const size_t kRounds = 24;
  for (size_t Round = 0; Round < kRounds; ++Round) {
    std::ostringstream Ctx;
    Ctx << "projection_combo round=" << Round;
    G_ctx = Ctx.str();
    JournalSpec Spec;
    size_t Total = 3 + Rng.Below(4);           // 3..6 files
    Spec.NumFirst = Rng.Below(static_cast<uint32_t>(Total));
    Spec.Files.resize(Total);
    for (size_t I = 0; I < Total; ++I) {
      auto &F = Spec.Files[I];
      F.Name = "c" + std::to_string(I);
      F.Size = 1 + Rng.Below(8);               // candidate byte lengths vary
      size_t NFeat = Rng.Below(4);
      for (size_t J = 0; J < NFeat; ++J)
        F.Features.push_back(1 + Rng.Below(20));
      size_t NPC = Rng.Below(3);
      for (size_t J = 0; J < NPC; ++J)
        F.PCs.push_back(100 + Rng.Below(15));
    }
    std::set<uint32_t> InitialFeatures, InitialPCs;
    for (uint32_t V = 1; V <= 20; ++V)
      if (Rng.Below(4) == 0)
        InitialFeatures.insert(V);
    for (uint32_t V = 100; V < 115; ++V)
      if (Rng.Below(5) == 0)
        InitialPCs.insert(V);
    std::string Log = BuildJournal(Spec, true);
    Merger M;
    std::set<uint32_t> NewFeat, NewPCs;
    std::set<std::string> Selected;
    CK(RunProductionMerge(Log, InitialFeatures, InitialPCs, &M, &NewFeat,
                          &NewPCs, &Selected) == 0);
    ModelJournal MJ = ParseModelJournal(Log, true);
    MergePrediction MP = PredictMerge(MJ, InitialFeatures, InitialPCs);
    CK(NewFeat == MP.NewFeatures);
    CK(NewPCs == MP.NewPCs);
    CK(CheckSelection(M, InitialFeatures, Selected, MP) == 0);
    // Nothing initial/old can leak into the new-feature projection.
    std::set<uint32_t> OldKnown = InitialFeatures;
    for (size_t I = 0; I < Spec.NumFirst; ++I)
      for (uint32_t Feat : Spec.Files[I].Features)
        OldKnown.insert(Feat);
    for (uint32_t Feat : NewFeat)
      CK(!OldKnown.count(Feat));
  }
  return 0;
}

