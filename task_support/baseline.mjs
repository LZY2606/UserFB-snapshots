import assert from 'node:assert/strict';
import { Project, PreviewRenderer, TimelineConverter, Transition } from '../src/index.js';
const p=new Project({fps:2,width:2,height:1});
const t=p.addTrack('video');
const normal=t.addVideo('memory:normal',{inPoint:4,outPoint:8,startTime:0});
const {head,tail}=normal.split(2);
assert.equal(head.outPoint,6); assert.equal(tail.inPoint,6);
assert.equal(t.getClips().length,2);
const representation=new TimelineConverter().convert(p);
assert.equal(representation.tracks[0].clips.length,2);
console.log(`normal_split=${head.inPoint}:${head.outPoint},${tail.inPoint}:${tail.outPoint}`);
const fast=t.addVideo('memory:fast',{inPoint:10,outPoint:18,startTime:4}); fast.speed(2);
console.log(`fast_duration=${fast.duration} track_duration=${t.getDuration()}`);
let clears=0,draws=0;
const backend={clear(){clears++},drawVideo(){draws++},getFrame(){return {width:2,height:1,data:new Uint8ClampedArray(8)}}};
const renderer=new PreviewRenderer(p.timeline,{backend});
const frame=await renderer.render(0.5);
assert.equal(clears,1); assert.equal(frame.width,2);
console.log(`preview_draws=${draws} preview_rgba=${Array.from(frame.data).join(',')}`);
const transition=new Transition('crossDissolve',2,{easing:'linear'});
assert.equal(transition.getProgressAt(1),0.5);
console.log('VIDEOF_TIMEBASE_OK normal_split=2 itr_clips=2 progress=0.5');
