import './historical-baseline.mjs';
import assert from 'node:assert/strict';
import { Object3D } from '../src/core/Object3D.js';
import { Mesh } from '../src/objects/Mesh.js';
import { BufferGeometry } from '../src/core/BufferGeometry.js';
import { Float32BufferAttribute } from '../src/core/BufferAttribute.js';
import { MeshBasicMaterial } from '../src/materials/MeshBasicMaterial.js';
import { Raycaster } from '../src/core/Raycaster.js';
import { Vector3 } from '../src/math/Vector3.js';
import { DoubleSide } from '../src/constants.js';
const root=new Object3D(),a=new Object3D(),b=new Object3D();root.add(a,b);
const geo=new BufferGeometry();geo.setAttribute('position',new Float32BufferAttribute([-1,-1,0,1,-1,0,0,1,0],3));
const material=new MeshBasicMaterial({side:DoubleSide});const one=new Mesh(geo,material),two=new Mesh(geo,material);a.add(one);b.add(two);b.position.x=4;root.updateMatrixWorld(true);
const ray=new Raycaster(new Vector3(0,0,5),new Vector3(0,0,-1),0,20);
let hits=ray.intersectObject(root,true);assert.equal(hits.length,1);assert.equal(hits[0].object,one);assert.equal(hits[0].distance,5);
let events=0;a.addEventListener('childremoved',()=>events++);b.add(one);root.updateMatrixWorld(true);assert.equal(events,1);assert.equal(ray.intersectObject(root,true).length,0);
b.position.x=0;root.updateMatrixWorld(true);hits=ray.intersectObject(root,true);assert.equal(hits.length,2);one.layers.set(2);assert.equal(ray.intersectObject(root,true).length,1);
root.visible=false;assert.equal(ray.intersectObject(root,true).length,1);
console.log('RAYCAST_LIFECYCLE_BASELINE_OK hits=1,0,2 layers=1 hidden=1 events=1');
