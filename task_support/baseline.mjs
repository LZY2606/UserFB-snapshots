import assert from 'node:assert/strict';
import '../checks/baseline.mjs';
import {Transform} from '../src/core/Transform.js';
import {GLTFAnimation} from '../src/extras/GLTFAnimation.js';
import {GLTFSkin} from '../src/extras/GLTFSkin.js';
import {Mat4} from '../src/math/Mat4.js';
const close=(a,b)=>assert.ok(Math.abs(a-b)<2e-6,`${a} != ${b}`);
const scene=new Transform(),root=new Transform(),knee=new Transform(),foot=new Transform();
scene.position.set(3,0,0);root.setParent(scene);knee.setParent(root);foot.setParent(knee);
knee.position.set(0,-1,0);foot.position.set(0,-1,0);scene.updateMatrixWorld(true);
for(const bone of [root,knee,foot]) bone.bindInverse=new Mat4(...bone.worldMatrix).inverse();
const animation=new GLTFAnimation([{node:root,transform:'position',interpolation:'LINEAR',times:[0,2],values:[0,0,0,4,0,0]}]);
animation.elapsed=1;animation.update(1,true);scene.updateMatrixWorld(true);
const skin=Object.create(GLTFSkin.prototype);
Object.assign(skin,{skeleton:{joints:[root,knee,foot]},boneMatrices:new Float32Array(48),boneTexture:{needsUpdate:false},boneTextureSize:4,program:{uniforms:{boneTexture:{},boneTextureSize:{}}}});
skin.updateUniforms();
close(root.worldMatrix[12],5);close(foot.worldMatrix[12],5);close(foot.worldMatrix[13],-2);
close(skin.boneMatrices[44],2);assert.equal(skin.program.uniforms.boneTexture.value,skin.boneTexture);
assert.equal(skin.boneTexture.needsUpdate,true);
const v=[3,-2,0,1],out=Array.from({length:4},(_,r)=>v.reduce((s,x,c)=>s+skin.boneMatrices[32+c*4+r]*x,0));
close(out[0],5);close(out[1],-2);close(out[3],1);
console.log('OGL_BASELINE_GLTF_WORLD_PALETTE_VERTEX_OK');
