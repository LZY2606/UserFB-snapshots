require('./build.cjs');
const assert=require('node:assert/strict');
const {parseAss,serializeAss}=require('../.task-build/formats/ass.js');
const {pasteCues}=require('../.task-build/edit-ops.js');
const doc=(size,text)=>`[Script Info]\nScriptType: v4.00+\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize\nStyle: Default,Arial,${size}\nStyle: Title,Arial,60\n\n[Events]\nFormat: Layer, Start, End, Style, Text\nDialogue: 0,0:00:01.00,0:00:03.00,Default,${text}\n`;
const source=parseAss(doc(72,'A{\\rTitle}B'));
const target=parseAss(doc(24,'target'));
const copied=structuredClone(source.cues);
const {cues,newIds}=pasteCues(target.cues,copied,0);
assert.equal(cues.length,2);assert.equal(newIds.length,1);
assert.notEqual(newIds[0],source.cues[0].id);
assert.equal(cues[1].startMs,3000);assert.equal(cues[1].endMs,5000);
assert.equal(cues[1].text,'A{\\rTitle}B');
const output=serializeAss({...target,cues});
const read=parseAss(output);
assert.equal(read.cues.length,2);assert.equal(read.cues[1].text,'A{\\rTitle}B');
console.log('NORMAL_PASTE_OK cues=2 start=3000 end=5000');
console.log('ASS_PERSISTENCE_OK kinds='+read.cues.map(c=>c.assKind).join(','));
console.log('STYLE_TRANSFER_OBSERVATION '+JSON.stringify({sourceSize:source.styles.find(s=>s.name==='Default').fields.Fontsize,pastedReference:read.cues[1].assFields.Style,resolvedTargetSize:read.styles.find(s=>s.name===read.cues[1].assFields.Style).fields.Fontsize,styleCount:read.styles.length}));
