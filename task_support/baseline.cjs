'use strict';
const assert=require('node:assert/strict');
require('../baseline/current.js');
const World=require('../src/goo/entities/World');
const TransformSystem=require('../src/goo/entities/systems/TransformSystem');
const System=require('../src/goo/entities/systems/System');
const world=new World();world.setSystem(new TransformSystem());
const watched=new System('MembershipProbe',['TransformComponent']);world.setSystem(watched);
const events=[];watched.inserted=e=>events.push(['in',e]);watched.deleted=e=>events.push(['out',e]);
const root=world.createEntity('root'),child=world.createEntity('child');
root.setTranslation(3,0,0);child.setTranslation(0,2,0);root.attachChild(child);
world.addEntity(root);assert.equal(world.entityManager.containsEntity(child),true);
assert.equal(watched._activeEntities.length,0);world.process();
assert.equal(watched._activeEntities.length,2);assert.equal(events.length,2);
assert.equal(child.transformComponent.worldTransform.translation.x,3);
assert.equal(child.transformComponent.worldTransform.translation.y,2);
root.setTranslation(5,0,0);world.process();
assert.equal(child.transformComponent.worldTransform.translation.x,5);
world.removeEntity(root);world.process();assert.equal(watched._activeEntities.length,0);
assert.equal(world.entityManager.containsEntity(child),false);
assert.equal(child.transformComponent.parent,root.transformComponent);
assert.equal(events.length,4);
world.addEntity(root);world.process();assert.equal(watched._activeEntities.length,2);
assert.equal(child.transformComponent.worldTransform.translation.x,5);
console.log('GOO_BASELINE_WORLD_MEMBERSHIP_EVENTS_TRANSFORM_OK');
