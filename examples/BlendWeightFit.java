import com.badlogic.gdx.graphics.g3d.Model;
import com.badlogic.gdx.graphics.g3d.ModelInstance;
import com.badlogic.gdx.graphics.g3d.model.Animation;
import com.badlogic.gdx.graphics.g3d.model.Node;
import com.badlogic.gdx.graphics.g3d.model.NodeAnimation;
import com.badlogic.gdx.graphics.g3d.model.NodeKeyframe;
import com.badlogic.gdx.graphics.g3d.model.NodePart;
import com.badlogic.gdx.graphics.g3d.utils.BlendWeightSolver;
import com.badlogic.gdx.graphics.g3d.utils.BlendWeightSolver.Evaluation;
import com.badlogic.gdx.graphics.g3d.utils.BlendWeightSolver.Observation;
import com.badlogic.gdx.graphics.g3d.utils.BlendWeightSolver.Preparation;
import com.badlogic.gdx.graphics.g3d.utils.BlendWeightSolver.Result;
import com.badlogic.gdx.math.Matrix4;
import com.badlogic.gdx.math.Quaternion;
import com.badlogic.gdx.math.Vector3;
import com.badlogic.gdx.utils.Array;
import com.badlogic.gdx.utils.ArrayMap;

/** Standalone demo of {@link BlendWeightSolver}: prepare skinned point observations, solve one simplex of clip weights
 * shared by the whole skeleton, apply the pose and then rebuild the same points from the real committed bone palette.
 * Run with the project classpath; prints {@code BLEND_WEIGHT_FIT_DEMO_OK} when every assertion holds. */
public final class BlendWeightFit {
	private static final int SLOTS = BlendWeightSolver.BONE_SLOTS;

	private BlendWeightFit () {
	}

	public static void main (final String[] args) {
		// ---- A tiny four-bone chain with non-commuting rest rotations. ----------------------
		final Model model = new Model();
		final Node root = node("root", null, new Vector3(0, 0, 0), new Quaternion().setFromAxis(0, 0, 1, 20f),
			new Vector3(1, 1, 1));
		final Node arm = node("arm", root, new Vector3(1, 0, 0), new Quaternion().setFromAxis(1, 0, 0, 35f),
			new Vector3(1, 1, 1));
		final Node hand = node("hand", arm, new Vector3(0, 1, 0), new Quaternion(), new Vector3(1.1f, 0.9f, 1.2f));
		final Node tip = node("tip", hand, new Vector3(0, 0, 1), new Quaternion().setFromAxis(0, 1, 0, -25f),
			new Vector3(1, 1, 1));
		model.nodes.add(root);
		model.calculateTransforms();

		final ModelInstance instance = new ModelInstance(model);
		// Affine (rotation + scale + translation) instance world transform.
		instance.transform.setToRotation(new Vector3(0, 1, 0), 40f).scale(1.05f, 0.95f, 1.1f).trn(2, -1, 3);
		final Node iRoot = instance.getNode("root");
		final Node iArm = instance.getNode("arm");
		final Node iHand = instance.getNode("hand");
		final Node iTip = instance.getNode("tip");

		// ---- A skinned part: four slots, non-unit inverse binds and a shuffled slot order. --
		final NodePart part = new NodePart();
		part.invBoneBindTransforms = new ArrayMap<>(Node.class, Matrix4.class);
		part.invBoneBindTransforms.put(iTip, new Matrix4().setToTranslation(0, -2, -1));
		part.invBoneBindTransforms.put(iRoot, new Matrix4().setToRotation(new Vector3(0, 0, 1), 15f));
		part.invBoneBindTransforms.put(iHand, new Matrix4().setToScaling(1.5f, 1.5f, 1.5f));
		part.invBoneBindTransforms.put(iArm, new Matrix4().setToTranslation(-1, -1, 0));
		part.bones = new Matrix4[SLOTS];
		for (int i = 0; i < SLOTS; i++)
			part.bones[i] = new Matrix4();
		iRoot.parts.add(part);

		// ---- Two clips with per-node TRS channels (missing channels fall back to rest). ----
		final Animation clipA = new Animation();
		clipA.id = "clipA";
		clipA.duration = 1f;
		final NodeAnimation aArm = new NodeAnimation();
		aArm.node = iArm;
		aArm.translation = vecKeys(0f, new Vector3(1, 0, 0), 1f, new Vector3(2, 0.5f, 0));
		aArm.rotation = quatKeys(0f, new Quaternion(), 1f, new Quaternion().setFromAxis(0, 0, 1, 80f));
		clipA.nodeAnimations.add(aArm);
		final NodeAnimation aHand = new NodeAnimation();
		aHand.node = iHand;
		aHand.scaling = vecKeys(0f, new Vector3(1, 1, 1), 1f, new Vector3(1.4f, 1.1f, 0.9f));
		clipA.nodeAnimations.add(aHand);

		final Animation clipB = new Animation();
		clipB.id = "clipB";
		clipB.duration = 2f;
		final NodeAnimation bTip = new NodeAnimation();
		bTip.node = iTip;
		bTip.translation = vecKeys(0f, new Vector3(0, 0, 1), 2f, new Vector3(0, 0, 2.5f));
		clipB.nodeAnimations.add(bTip);
		final NodeAnimation bRoot = new NodeAnimation();
		bRoot.node = iRoot;
		bRoot.rotation = quatKeys(0f, new Quaternion().setFromAxis(0, 0, 1, 20f), 2f,
			new Quaternion().setFromAxis(0, 0, 1, 110f));
		clipB.nodeAnimations.add(bRoot);

		final Animation[] clips = {clipA, clipB};
		final float[] times = {0.5f, 1.0f};
		model.animations.addAll(clipA, clipB);
		instance.copyAnimations(model.animations);

		// ---- One skinned observation whose target was generated by a known weight vector. --
		final double[] star = {0.7, 0.3};
		final int[] slots = {0, 1, 2, 3};
		final float[] skin = {0.35f, 0.25f, 0.25f, 0.15f};
		final Vector3 bindPoint = new Vector3(0.3f, -0.4f, 0.6f);
		final Observation generator = new Observation();
		generator.part = part;
		generator.bindPoint.set(bindPoint);
		generator.setBoneSlots(slots);
		generator.setSkinWeights(skin);
		generator.weight = 1f;
		final Preparation generatorPrep = BlendWeightSolver.prepare(instance, clips, times,
			new Observation[] {generator});
		final Evaluation generated = generatorPrep.evaluate(star);

		final Observation observation = new Observation();
		observation.part = part;
		observation.bindPoint.set(bindPoint);
		observation.setBoneSlots(slots);
		observation.setSkinWeights(skin);
		observation.target.set((float)generated.worldPoints[0], (float)generated.worldPoints[1],
			(float)generated.worldPoints[2]);
		observation.weight = 1f;

		// ---- 1) Prepare: inputs are snapshotted; evaluation never writes the instance. ------
		final Preparation preparation = BlendWeightSolver.prepare(instance, clips, times,
			new Observation[] {observation});
		final Evaluation before = preparation.evaluate(new double[] {0.5, 0.5});
		System.out.printf("initial world point = (%.5f, %.5f, %.5f)%n", before.worldPoints[0], before.worldPoints[1],
			before.worldPoints[2]);
		System.out.printf("jacobian row layout  = %d clips x 3 axes, length %d%n", preparation.clipCount(),
			before.jacobian[0].length);

		// ---- 2) Solve on the simplex and apply through the real transform pipeline. --------
		final double[] prior = {0.5, 0.5};
		final double lambda = 0.001;
		final Result result = BlendWeightSolver.solveAndApply(preparation, new double[] {0.5, 0.5}, prior, lambda, 1e-9,
			400);
		System.out.printf("solved weights       = (%.5f, %.5f), F=%.3e, accepted=%d, residual=%.3e, converged=%b%n",
			result.weights[0], result.weights[1], result.objective, result.acceptedIterations,
			result.projectedGradientResidual, result.converged);

		// ---- 3) Rebuild the point from the real palette the renderer would consume. --------
		final Vector3 paletteModel = new Vector3();
		for (int j = 0; j < SLOTS; j++) {
			final Vector3 skinned = new Vector3(bindPoint).mul(part.bones[observation.boneSlots[j]]);
			paletteModel.x += skin[j] * skinned.x;
			paletteModel.y += skin[j] * skinned.y;
			paletteModel.z += skin[j] * skinned.z;
		}
		final Vector3 paletteWorld = paletteModel.mul(instance.transform);
		System.out.printf("palette world point  = (%.5f, %.5f, %.5f)%n", paletteWorld.x, paletteWorld.y, paletteWorld.z);
		final Evaluation solved = preparation.evaluate(result.weights);

		// ---- Assertions. --------------------------------------------------------------------
		require(result.converged, "solver must report convergence on the consistent system");
		require(Math.abs(result.weights[0] - star[0]) < 0.02, "weights must recover the generating blend");
		// The target is exactly reachable, so the remaining objective is just the regularization at the generating point.
		double regularizationAtStar = 0.0;
		for (int k = 0; k < star.length; k++)
			regularizationAtStar += (star[k] - prior[k]) * (star[k] - prior[k]);
		regularizationAtStar = 0.5 * lambda * regularizationAtStar;
		require(result.objective <= regularizationAtStar + 1e-8,
			"objective must reach the regularization floor of the generating point");
		// The real palette the renderer uses must reproduce the no-write candidate evaluation at the solved weights.
		for (int axis = 0; axis < 3; axis++) {
			final double actual = axis == 0 ? paletteWorld.x : axis == 1 ? paletteWorld.y : paletteWorld.z;
			require(Math.abs(actual - solved.worldPoints[axis]) < 2e-4,
				"real palette point must match the candidate evaluation");
			require(Math.abs(actual - generated.worldPoints[axis]) < 1e-2,
				"committed point must stay close to the generating target");
		}
		System.out.println("BLEND_WEIGHT_FIT_DEMO_OK");
	}

	private static Node node (final String id, final Node parent, final Vector3 translation, final Quaternion rotation,
		final Vector3 scale) {
		final Node node = new Node();
		node.id = id;
		node.translation.set(translation);
		node.rotation.set(rotation);
		node.scale.set(scale);
		if (parent != null) parent.addChild(node);
		return node;
	}

	private static Array<NodeKeyframe<Vector3>> vecKeys (final Object... kv) {
		final Array<NodeKeyframe<Vector3>> frames = new Array<>();
		for (int i = 0; i < kv.length; i += 2)
			frames.add(new NodeKeyframe<Vector3>(((Number)kv[i]).floatValue(), (Vector3)kv[i + 1]));
		return frames;
	}

	private static Array<NodeKeyframe<Quaternion>> quatKeys (final Object... kv) {
		final Array<NodeKeyframe<Quaternion>> frames = new Array<>();
		for (int i = 0; i < kv.length; i += 2)
			frames.add(new NodeKeyframe<Quaternion>(((Number)kv[i]).floatValue(), (Quaternion)kv[i + 1]));
		return frames;
	}

	private static void require (final boolean condition, final String message) {
		if (!condition) throw new AssertionError(message);
	}
}
