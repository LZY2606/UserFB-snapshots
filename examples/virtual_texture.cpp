// Sparse virtual texturing example.
//
// Two procedurally generated 16x16 textures (only the uploaded page pixels are
// ever stored) and two triangles that overlap on screen are rendered twice:
//   1. against a snapshot holding just the coarse 4x4 mip page, so the ideal
//      level-0 fetch falls back to a blurry level and every fine page touched
//      by a visible fragment is reported as missing;
//   2. after streaming exactly the pages from that feedback list, so the same
//      scene is sampled sharply and the feedback list is empty.
//
// Usage: virtual_texture <output-directory>
// The program writes before_loading.tga, after_loading.tga and
// missing_pages.txt there, and prints a short summary on stdout.
#include "virtual_texture.h"
#include "tgaimage.h"

#include <cmath>
#include <cstdint>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

using namespace vt;

namespace {

constexpr int IMG = 64;          // frame size
constexpr int SIDE = 16;         // texture base size
constexpr int PAGE = 4;          // page edge in texels
constexpr int TEX_A = 0;
constexpr int TEX_B = 1;

// Procedural linear-RGB texels, evaluated on demand: the example never keeps a
// full logical image, the pool only ever stores uploaded page pixels.
vec3 texel(int texture, int x, int y) {
    const int block = (x / PAGE + y / PAGE) % 2;
    if (texture == TEX_A) // warm red/orange checker
        return block ? vec3{0.95, 0.55, 0.15} : vec3{0.80, 0.12, 0.10};
    return block ? vec3{0.10, 0.45, 0.95} : vec3{0.05, 0.15, 0.60}; // cool blue checker
}

PageUpload build_page(const VirtualTexturePool &pool, int texture,
                      int level, int px, int py) {
    PageUpload up;
    up.key = {texture, level, px, py};
    up.width = pool.page_width(texture, level, px);
    up.height = pool.page_height(texture, level, py);
    up.rgb.resize(static_cast<size_t>(up.width) * up.height * 3);
    // Coarser mips are generated by nearest reduction of the base pattern, so
    // every level stays self-consistent without storing a full image.
    const int scale = SIDE / pool.level_width(texture, level);
    for (int y = 0; y < up.height; ++y)
        for (int x = 0; x < up.width; ++x) {
            const vec3 c = texel(texture, (px * PAGE + x) * scale,
                                 (py * PAGE + y) * scale);
            const size_t k = (static_cast<size_t>(y) * up.width + x) * 3;
            up.rgb[k] = c[0]; up.rgb[k + 1] = c[1]; up.rgb[k + 2] = c[2];
        }
    return up;
}

mat<4,4> viewport() {
    return mat<4,4>{{{IMG / 2., 0., 0., IMG / 2.},
                     {0., IMG / 2., 0., IMG / 2.},
                     {0., 0., 1., 0.}, {0., 0., 0., 1.}}};
}

// Two triangles overlap in a vertical center band. The warm triangle is nearer
// (larger z/w wins) and occludes the cool one there; outside the band each is
// visible on its own, so both textures appear in every frame.
void submit_scene(VirtualTextureFrame &frame) {
    const vec2 full_a[3] = {{0., 0.}, {1., 0.}, {0., 1.}};
    const vec2 full_b[3] = {{1., 0.}, {1., 1.}, {0., 1.}};
    const vec4 warm[3] = {{-1., -1., 0.7, 1.}, {0.35, -1., 0.7, 1.},
                          {-1.,  1., 0.7, 1.}};
    const vec4 cool[3] = {{ 1.,  1., 0.3, 1.}, {-0.35, 1., 0.3, 1.},
                          { 1., -1., 0.3, 1.}};
    frame.submit_triangle(TEX_A, false, warm, full_a);
    frame.submit_triangle(TEX_B, false, cool, full_b);
}

void write_tga(const std::string &path, const VirtualTextureFrame &frame) {
    TGAImage image(IMG, IMG, TGAImage::RGB);
    auto to_byte = [](double v) {
        v = std::clamp(v, 0.0, 1.0);
        return static_cast<std::uint8_t>(std::lround(v * 255.0));
    };
    for (int y = 0; y < IMG; ++y)
        for (int x = 0; x < IMG; ++x) {
            const FragmentInfo &f = frame.fragment(x, y);
            TGAColor c;
            c.bytespp = TGAImage::RGB;
            c.bgra[0] = to_byte(f.b); // TGA byte order is B, G, R
            c.bgra[1] = to_byte(f.g);
            c.bgra[2] = to_byte(f.r);
            image.set(x, y, c);
        }
    if (!image.write_tga_file(path))
        throw std::runtime_error("cannot write " + path);
}

void dump_list(const std::vector<PageKey> &pages,
               const char *title, std::ofstream &out) {
    out << "# " << title << " (" << pages.size() << " pages)\n";
    for (const PageKey &k : pages)
        out << "texture=" << k.texture_id << " level=" << k.level
            << " page_y=" << k.page_y << " page_x=" << k.page_x << '\n';
    out << '\n';
    std::cout << title << ": " << pages.size() << " missing page(s)\n";
}

} // namespace

int main(int argc, char **argv) {
    if (argc != 2) {
        std::cerr << "usage: " << argv[0] << " <output-directory>\n";
        return 1;
    }
    const std::filesystem::path dir = argv[1];
    std::filesystem::create_directories(dir);

    VirtualTexturePool pool(std::vector<TextureDesc>{
        {TEX_A, SIDE, SIDE, PAGE}, {TEX_B, SIDE, SIDE, PAGE}});

    // Initial residency: the pinned 1x1 page plus the coarse 4x4 mip (level 2),
    // so missing fine pages fall back exactly two levels instead of going black.
    for (int tex : {TEX_A, TEX_B})
        pool.upload(build_page(pool, tex, 2, 0, 0));

    const std::string list_path = (dir / "missing_pages.txt").string();
    std::ofstream list(list_path);
    if (!list) throw std::runtime_error("cannot write " + list_path);

    // --- Pass 1: coarse residency -------------------------------------------
    {
        VirtualTextureFrame frame(IMG, IMG, viewport(), pool.snapshot());
        submit_scene(frame);
        frame.generate();
        write_tga((dir / "before_loading.tga").string(), frame);
        dump_list(frame.missing_pages(), "before loading", list);

        // Stream exactly the pages the visible fragments asked for.
        for (const PageKey &k : frame.missing_pages())
            pool.upload(build_page(pool, k.texture_id, k.level, k.page_x, k.page_y));
    }

    // --- Pass 2: every requested page is now resident -----------------------
    {
        VirtualTextureFrame frame(IMG, IMG, viewport(), pool.snapshot());
        submit_scene(frame);
        frame.generate();
        write_tga((dir / "after_loading.tga").string(), frame);
        dump_list(frame.missing_pages(), "after loading", list);

        int warm = 0, cool = 0;
        for (int y = 0; y < IMG; ++y)
            for (int x = 0; x < IMG; ++x) {
                const int face = frame.fragment(x, y).face;
                if (face == 0) ++warm;
                if (face == 1) ++cool;
            }
        std::cout << "visible fragments: warm triangle=" << warm
                  << " cool triangle=" << cool << "\n";
        const FragmentInfo &sample = frame.fragment(IMG / 2, IMG / 4);
        std::cout << "sample fragment face=" << sample.face
                  << " lod=" << sample.lod
                  << " used_level0=" << sample.used_level0
                  << " used_level1=" << sample.used_level1 << '\n';
    }

    std::cout << "wrote " << (dir / "before_loading.tga").string() << ", "
              << (dir / "after_loading.tga").string() << " and " << list_path
              << '\n';
    return 0;
}
